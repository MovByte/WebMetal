//! With the `native` feature, binds the webgpu.h C API of a native WebGPU implementation.
//!
//! The implementation is chosen at build time:
//!
//! - `WEBGPU_NATIVE`: `dawn` or `wgpu-native`.
//! - `WEBGPU_NATIVE_DIR`: its install root, holding `include/webgpu/webgpu.h` and `lib/`. Dawn is linked statically
//!   (`lib/libwebgpu_dawn.a`, the layout of Dawn's release archives and of `cmake --install`); wgpu-native
//!   dynamically (`lib/libwgpu_native.dylib` or `.so`, the layout of its release archives), with the directory added to
//!   the run-time search path.
//!
//! The Rust declarations are generated by bindgen from that implementation's own header, so every structure layout,
//! enumerator and function signature is the one the linked library was built with. The build fails when the feature is
//! on and either variable is missing.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    #[cfg(feature = "native")]
    native::bind();
    println!("cargo:rustc-check-cfg=cfg(webgpu_native, values(\"dawn\", \"wgpu-native\"))");
}

#[cfg(feature = "native")]
mod native {
    use std::env;
    use std::fs;
    use std::path::{Path, PathBuf};
    use std::process::Command;

    /// The wgpu-native release whose unimplemented entry points (src/unimplemented.rs) the binding was written against.
    const WGPU_NATIVE_CHECKED: &str = "v29.0.1.1";

    fn var(name: &str) -> String {
        println!("cargo:rerun-if-env-changed={name}");
        match env::var(name) {
            Ok(v) if !v.is_empty() => v,
            _ => panic!(
                "the `native` feature needs {name}: set WEBGPU_NATIVE to `dawn` or `wgpu-native` and WEBGPU_NATIVE_DIR to \
                 the implementation's install root (with include/webgpu/webgpu.h and lib/)"
            ),
        }
    }

    pub fn bind() {
        let which = var("WEBGPU_NATIVE");
        let root = PathBuf::from(var("WEBGPU_NATIVE_DIR"));
        let include = root.join("include");
        let lib = root.join("lib");
        let header = include.join("webgpu").join("webgpu.h");
        if !header.is_file() {
            panic!("{} does not exist", header.display());
        }
        let mut wrapper = String::from("#include <webgpu/webgpu.h>\n");

        let version = match which.as_str() {
            "dawn" => {
                let archive = lib.join("libwebgpu_dawn.a");
                if !archive.is_file() {
                    panic!("{} does not exist", archive.display());
                }
                println!("cargo:rerun-if-changed={}", archive.display());
                println!("cargo:rustc-link-search=native={}", lib.display());
                println!("cargo:rustc-link-lib=static=webgpu_dawn");
                if cfg!(target_os = "macos") || env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
                    println!("cargo:rustc-link-lib=c++");
                    // The frameworks Dawn's exported CMake target links (lib/cmake/Dawn/DawnTargets.cmake).
                    for fw in ["CoreFoundation", "Foundation", "IOSurface", "QuartzCore", "Cocoa", "IOKit", "Metal"] {
                        println!("cargo:rustc-link-lib=framework={fw}");
                    }
                } else {
                    println!("cargo:rustc-link-lib=stdc++");
                }
                dawn_version(&include, &root)
            }
            "wgpu-native" => {
                wrapper.push_str("#include <webgpu/wgpu.h>\n");
                let dylib =
                    ["libwgpu_native.dylib", "libwgpu_native.so"].iter().map(|n| lib.join(n)).find(|p| p.is_file());
                let Some(dylib) = dylib else { panic!("no libwgpu_native.dylib or .so in {}", lib.display()) };
                println!("cargo:rerun-if-changed={}", dylib.display());
                println!("cargo:rustc-link-search=native={}", lib.display());
                println!("cargo:rustc-link-lib=dylib=wgpu_native");
                println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
                let tag = root.join("wgpu-native-meta").join("wgpu-native-git-tag");
                let tag = fs::read_to_string(&tag).map(|t| t.trim().to_string()).unwrap_or_default();
                if tag != WGPU_NATIVE_CHECKED {
                    println!(
                        "cargo:warning=linking wgpu-native {tag:?}; the binding's list of entry points wgpu-native does not \
                         implement was read from {WGPU_NATIVE_CHECKED} and must be checked against this release"
                    );
                }
                format!("wgpu-native {tag}")
            }
            other => panic!("WEBGPU_NATIVE must be `dawn` or `wgpu-native`, not `{other}`"),
        };
        println!("cargo:rustc-cfg=webgpu_native=\"{which}\"");
        println!("cargo:rerun-if-changed={}", header.display());

        let out = PathBuf::from(env::var("OUT_DIR").unwrap());
        let mut builder = bindgen::Builder::default()
            .header_contents("webmetal_webgpu.h", &wrapper)
            .clang_arg(format!("-I{}", include.display()))
            .allowlist_function("wgpu.*")
            .allowlist_type("WGPU.*")
            .allowlist_var("WGPU.*")
            .prepend_enum_name(false)
            .default_enum_style(bindgen::EnumVariation::Consts)
            .layout_tests(true)
            .derive_default(false)
            .generate_comments(false);
        if let Some(sdk) = macos_sdk() {
            builder = builder.clang_arg(format!("-isysroot{sdk}"));
        }
        let bindings = builder.generate().expect("bindgen could not process webgpu.h");
        bindings.write_to_file(out.join("webgpu_sys.rs")).expect("write webgpu_sys.rs");
        let text = fs::read_to_string(out.join("webgpu_sys.rs")).unwrap();

        // Every enumerator of every enum of the header, so the binding can map IDL enum values to them by name.
        let mut meta = String::new();
        meta.push_str(&format!(
            "/// The implementation and version this build links.\npub const IMPLEMENTATION: &str = {version:?};\n"
        ));
        meta.push_str(&format!(
            "/// The header bindgen read.\npub const HEADER: &str = {:?};\n",
            header.display().to_string()
        ));
        meta.push_str("/// Every enumerator of the header: (enum type, enumerator name after the `_`, value).\n");
        meta.push_str("pub const C_ENUMS: &[(&str, &str, u32)] = &[\n");
        let mut n = 0;
        for line in text.lines() {
            let l = line.trim();
            let Some(rest) = l.strip_prefix("pub const WGPU") else { continue };
            let Some((name, rest)) = rest.split_once(": WGPU") else { continue };
            let Some((ty, value)) = rest.split_once(" = ") else { continue };
            let value = value.trim_end_matches(';');
            let Some((ename, suffix)) = name.split_once('_') else { continue };
            if ename != ty {
                continue;
            }
            let v: u64 = if let Some(h) = value.strip_prefix("0x") {
                u64::from_str_radix(h, 16).unwrap()
            } else {
                match value.parse() {
                    Ok(v) => v,
                    Err(_) => continue,
                }
            };
            if v > u64::from(u32::MAX) {
                continue;
            }
            meta.push_str(&format!("    (\"WGPU{ty}\", {suffix:?}, {v}),\n"));
            n += 1;
        }
        meta.push_str("];\n");
        assert!(n > 100, "found only {n} enumerators in the bindgen output");
        fs::write(out.join("webgpu_meta.rs"), meta).unwrap();
    }

    fn dawn_version(include: &Path, root: &Path) -> String {
        let name = root.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
        let header = include.join("dawn").join("dawn_version.h");
        let minor = fs::read_to_string(&header).ok().and_then(|t| {
            t.lines().find_map(|l| l.strip_prefix("#define DAWN_MINOR_VERSION ").map(|v| v.trim().to_string()))
        });
        match minor {
            Some(m) => format!("Dawn {name} (DAWN_MINOR_VERSION {m})"),
            None => format!("Dawn {name}"),
        }
    }

    fn macos_sdk() -> Option<String> {
        if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("macos") {
            return None;
        }
        println!("cargo:rerun-if-env-changed=SDKROOT");
        if let Ok(s) = env::var("SDKROOT") {
            return Some(s);
        }
        let out = Command::new("xcrun").args(["--sdk", "macosx", "--show-sdk-path"]).output().ok()?;
        out.status.success().then(|| String::from_utf8_lossy(&out.stdout).trim().to_string())
    }
}
