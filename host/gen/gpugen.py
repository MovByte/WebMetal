TOKEN_RE = re.compile(r'\s+|//[^\n]*|"[^"]*"|0[xX][0-9a-fA-F]+|-?\d+(?:\.\d+)?|[A-Za-z_][A-Za-z0-9_]*|\.\.\.|[{}()\[\]<>,;:=?]')


def tokenize(text):
    out = []
    pos = 0
    while pos < len(text):
        m = TOKEN_RE.match(text, pos)
        if not m:
            raise SystemExit("IDL: cannot tokenize at %r" % text[pos:pos + 40])
        tok = m.group(0)
        pos = m.end()
        if tok.isspace() or tok.startswith("//"):
            continue
        out.append(tok)
    return out


class Type:
    """An IDL type: kind is 'named', 'sequence', 'record', 'promise', 'frozen', 'union', 'setlike'."""

    def __init__(self, kind, name=None, args=None, nullable=False, ext=None):
        self.kind = kind
        self.name = name
        self.args = args or []
        self.nullable = nullable
        self.ext = ext or []

    def text(self):
        if self.kind == "named":
            s = self.name
        elif self.kind == "union":
            s = "(" + " or ".join(a.text() for a in self.args) + ")"
        else:
            s = "%s<%s>" % ({"sequence": "sequence", "record": "record", "promise": "Promise", "frozen": "FrozenArray"}[self.kind],
                            ", ".join(a.text() for a in self.args))
        if self.ext:
            s = "[%s] %s" % (", ".join(self.ext), s)
        return s + ("?" if self.nullable else "")


class Parser:
    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self, k=0):
        return self.t[self.i + k] if self.i + k < len(self.t) else None

    def take(self, want=None):
        tok = self.peek()
        if want is not None and tok != want:
            raise SystemExit("IDL: expected %r, found %r near %r" % (want, tok, self.t[max(0, self.i - 8):self.i + 8]))
        self.i += 1
        return tok

    def ext_attrs(self):
        attrs = []
        if self.peek() == "[":
            self.take("[")
            depth = 1
            cur = []
            while depth:
                tok = self.take()
                if tok == "[":
                    depth += 1
                elif tok == "]":
                    depth -= 1
                    if depth == 0:
                        break
                if tok == "," and depth == 1:
                    attrs.append(" ".join(cur))
                    cur = []
                else:
                    cur.append(tok)
            if cur:
                attrs.append(" ".join(cur))
        return [a.replace(" ( ", "(").replace(" )", ")").replace(" , ", ", ") for a in attrs]

    def type_(self):
        ext = self.ext_attrs()
        if self.peek() == "(":
            self.take("(")
            members = [self.type_()]
            while self.peek() == "or":
                self.take("or")
                members.append(self.type_())
            self.take(")")
            t = Type("union", args=members, ext=ext)
        else:
            name = self.take()
            if name in ("unsigned", "unrestricted"):
                name = name + " " + self.take()
                if name == "unsigned long" and self.peek() == "long":
                    name = "unsigned long long"
                    self.take()
            elif name == "long" and self.peek() == "long":
                self.take()
                name = "long long"
            kinds = {"sequence": "sequence", "record": "record", "Promise": "promise", "FrozenArray": "frozen",
                     "setlike": "setlike"}
            if name in kinds and self.peek() == "<":
                self.take("<")
                args = [self.type_()]
                while self.peek() == ",":
                    self.take(",")
                    args.append(self.type_())
                self.take(">")
                t = Type(kinds[name], args=args, ext=ext)
            else:
                t = Type("named", name=name, ext=ext)
        if self.peek() == "?":
            self.take("?")
            t.nullable = True
        return t

    def value(self):
        tok = self.take()
        if tok == "[":
            self.take("]")
            return "[]"
        if tok == "{":
            self.take("}")
            return "{}"
        return tok

    def definitions(self):
        defs = []
        while self.peek() is not None:
            ext = self.ext_attrs()
            tok = self.peek()
            if tok == "interface" and self.peek(1) == "mixin":
                self.take()
                self.take()
                defs.append(self.interface("mixin", ext))
            elif tok == "interface":
                self.take()
                defs.append(self.interface("interface", ext))
            elif tok == "partial":
                self.take()
                self.take("interface")
                defs.append(self.interface("partial", ext))
            elif tok == "dictionary":
                self.take()
                defs.append(self.dictionary())
            elif tok == "enum":
                self.take()
                name = self.take()
                self.take("{")
                values = []
                while self.peek() != "}":
                    v = self.take()
                    if v != ",":
                        values.append(v.strip('"'))
                self.take("}")
                self.take(";")
                defs.append({"def": "enum", "name": name, "values": values})
            elif tok == "typedef":
                self.take()
                t = self.type_()
                name = self.take()
                self.take(";")
                defs.append({"def": "typedef", "name": name, "type": t})
            elif tok == "namespace":
                self.take()
                defs.append(self.namespace(ext))
            else:
                # "A includes B;"
                a = self.take()
                self.take("includes")
                b = self.take()
                self.take(";")
                defs.append({"def": "includes", "target": a, "mixin": b})
        return defs

    def interface(self, kind, ext):
        name = self.take()
        base = None
        if self.peek() == ":":
            self.take(":")
            base = self.take()
        self.take("{")
        members = []
        while self.peek() != "}":
            mext = self.ext_attrs()
            tok = self.peek()
            if tok == "constructor":
                self.take()
                args = self.arguments()
                self.take(";")
                members.append({"kind": "constructor", "name": "constructor", "args": args, "ext": mext})
                continue
            if tok == "const":
                self.take()
                t = self.type_()
                n = self.take()
                self.take("=")
                v = self.value()
                self.take(";")
                members.append({"kind": "const", "name": n, "type": t, "value": v})
                continue
            readonly = False
            if tok == "readonly":
                self.take()
                readonly = True
                tok = self.peek()
            if tok == "setlike":
                t = self.type_()
                self.take(";")
                members.append({"kind": "setlike", "name": "setlike", "type": t, "readonly": readonly})
                continue
            if tok == "attribute":
                self.take()
                t = self.type_()
                n = self.take()
                self.take(";")
                members.append({"kind": "attribute", "name": n, "type": t, "readonly": readonly, "ext": mext})
                continue
            t = self.type_()
            n = self.take()
            args = self.arguments()
            self.take(";")
            members.append({"kind": "operation", "name": n, "type": t, "args": args, "ext": mext})
        self.take("}")
        self.take(";")
        return {"def": kind, "name": name, "base": base, "members": members, "ext": ext}

    def arguments(self):
        self.take("(")
        args = []
        while self.peek() != ")":
            aext = self.ext_attrs()
            optional = False
            if self.peek() == "optional":
                self.take()
                optional = True
            t = self.type_()
            if aext:
                t.ext = aext + t.ext
            n = self.take()
            default = None
            if self.peek() == "=":
                self.take("=")
                default = self.value()
            args.append({"name": n, "type": t, "optional": optional, "default": default})
            if self.peek() == ",":
                self.take(",")
        self.take(")")
        return args

    def dictionary(self):
        name = self.take()
        base = None
        if self.peek() == ":":
            self.take(":")
            base = self.take()
        self.take("{")
        members = []
        while self.peek() != "}":
            required = False
            if self.peek() == "required":
                self.take()
                required = True
            t = self.type_()
            n = self.take()
            default = None
            if self.peek() == "=":
                self.take("=")
                default = self.value()
            self.take(";")
            members.append({"name": n, "type": t, "required": required, "default": default})
        self.take("}")
        self.take(";")
        return {"def": "dictionary", "name": name, "base": base, "members": members}

    def namespace(self, ext):
        name = self.take()
        self.take("{")
        consts = []
        while self.peek() != "}":
            self.take("const")
            t = self.type_()
            n = self.take()
            self.take("=")
            v = self.value()
            self.take(";")
            consts.append({"name": n, "type": t, "value": v})
        self.take("}")
        self.take(";")
        return {"def": "namespace", "name": name, "consts": consts, "ext": ext}


