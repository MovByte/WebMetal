#!/usr/bin/env python3
"""Generate the WebGPU binding layer's IDL-derived Rust from the pinned specification.

Sources:
- The IDL index of the WebGPU specification pinned as `webgpu` in tables/sources.toml
  (read and hash-checked through tables/gen/specdoc.py).
- tables/limits.toml: the limit and feature lists with their classes, defaults and
  dependencies. The limit list must name exactly the attributes of the IDL interface
  GPUSupportedLimits, and the feature list exactly the values of GPUFeatureName.
- tables/formats.toml: the "Required Feature" of every WebGPU texture format.
- The GPUBlendFactor table of the specification: the feature each blend factor requires.

Outputs:
- host/src/gpu/idl.rs: every enum, flag namespace, dictionary and union typedef of the
  IDL as Rust types, the GPUSupportedLimits and GPUAdapterInfo attribute sets, and the
  inventory of interface members that host/src/gpu/api.rs must account for.
- host/src/gpu/tables.rs: the limit, feature, format-feature and blend-factor tables.
- host/src/gpu/web/dict.rs: conversion of every dictionary to a JavaScript object, with
  the IDL member names, for the browser implementation.

Usage: gpugen.py --cache DIR [--check]
  --check regenerates in memory and exits 1 if a committed output differs.
"""

