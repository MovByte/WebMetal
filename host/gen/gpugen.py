def idl_index(doc):
    """The IDL index block: the last IDL block of the document, which must contain every other."""
    blocks = [b for b in doc.idl]
    index = blocks[-1]
    norm_index = specdoc.norm(index)
    for b in blocks[:-1]:
        nb = specdoc.norm(b)
        if nb not in norm_index:
            raise SystemExit("IDL block not in the IDL index: %s" % nb[:120])
    return index


def blend_feature_rows(doc, model):
    for t in doc.tables:
        g = t.grid()
        if g and g[0] and [c["text"] for c in g[0]] == ["GPUBlendFactor", "Blend factor RGBA components", "Feature"]:
            rows = []
            for r in g[1:]:
                v = r[0]["text"].strip('"')
                feat = r[2]["text"].strip('"') or None
                rows.append((v, feat))
            if [v for v, _ in rows] != model.enums["GPUBlendFactor"]["values"]:
                raise SystemExit("GPUBlendFactor table rows differ from the enum")
            return rows
    raise SystemExit("GPUBlendFactor table not found")


def feature_format_lists(doc, model):
    """{feature: [formats]} from the "New GPUTextureFormat enum values" list of each feature index section."""
    out = {}
    formats = set(model.enums["GPUTextureFormat"]["values"])
    for feat in model.enums["GPUFeatureName"]["values"]:
        anchor = feat if feat in doc.anchors else "dom-gpufeaturename-" + feat
        text = doc.scope(anchor)
        if text is None:
            raise SystemExit("no feature index section for %s" % feat)
        i = text.find("New GPUTextureFormat enum values")
        if i < 0:
            continue
        names = re.findall(r'"([^"]+)"', text[i:])
        bad = [n for n in names if n not in formats]
        if bad or not names:
            raise SystemExit("feature %s lists %s as new texture formats" % (feat, bad or "nothing"))
        out[feat] = names
    return out


def check_limits(model, limits_toml):
    idl = [m["name"] for _, m in model.interface_members("GPUSupportedLimits") if m["kind"] == "attribute"]
    tab = [l["name"] for l in limits_toml["limit"]]
    if sorted(idl) != sorted(tab):
        raise SystemExit("tables/limits.toml limits %s differ from GPUSupportedLimits %s" % (sorted(set(tab) ^ set(idl)), ""))
    for _, m in model.interface_members("GPUSupportedLimits"):
        row = next(l for l in limits_toml["limit"] if l["name"] == m["name"])
        want = "unsigned long long" if row["type"] == "GPUSize64" else "unsigned long"
        if m["type"].name != want:
            raise SystemExit("limit %s: IDL type %s, table type %s" % (m["name"], m["type"].name, row["type"]))
    feats = [f["name"] for f in limits_toml["feature"]]
    if feats != model.enums["GPUFeatureName"]["values"]:
        raise SystemExit("tables/limits.toml features differ from GPUFeatureName")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", default=os.environ.get("TABLES_CACHE"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    sources = specdoc.load_sources()
    doc = specdoc.document("webgpu", sources, a.cache)
    spec_ver = "%s %s" % (sources["webgpu"]["version"], sources["webgpu"]["date"])
    model = Model(Parser(tokenize(idl_index(doc))).definitions())
    with open(os.path.join(ROOT, "tables", "limits.toml"), "rb") as f:
        limits_toml = tomllib.load(f)
    with open(os.path.join(ROOT, "tables", "formats.toml"), "rb") as f:
        formats_toml = tomllib.load(f)
    check_limits(model, limits_toml)
    types = RustTypes(model)
    outputs = {
        OUT_IDL: emit_idl(model, types, limits_toml, spec_ver),
        OUT_TABLES: emit_tables(model, limits_toml, formats_toml, feature_format_lists(doc, model), blend_feature_rows(doc, model), spec_ver),
        OUT_WEB: emit_web(model, types, spec_ver),
    }
    stale = []
    for path, text in outputs.items():
        text = text.rstrip("\n") + "\n"
        if a.check:
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() != text:
                        stale.append(path)
            except FileNotFoundError:
                stale.append(path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    if stale:
        for p in stale:
            print("stale: %s" % os.path.relpath(p, ROOT), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
