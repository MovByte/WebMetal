def doc_lines(text, indent=""):
    return ["%s/// %s" % (indent, line) if line else "%s///" % indent for line in text.split("\n")]


def emit_idl(model, types, limits_toml, spec_ver):
    out = [HEADER.format(ver=spec_ver, tables="limits.toml"), ""]
    out.append("//! The WebGPU IDL as Rust types: enums, flag namespaces, dictionaries and union typedefs.")
    out.append("//!")
    out.append("//! Names drop the `GPU` prefix; dictionary members are in snake case and keep the IDL name in their")
    out.append("//! documentation. A member with an IDL default holds that default after `new()`; a member without one is")
    out.append("//! an `Option`, `None` meaning the member is not present. IDL numeric types map to the Rust type with")
    out.append("//! the same domain; `[EnforceRange] unsigned long long` and the restricted `float` and `double` types,")
    out.append("//! whose domains no Rust primitive has, map to [`Size64`], [`Float32`] and [`Float64`].")
    out.append("")
    out.append("#![allow(clippy::too_many_arguments, clippy::new_without_default)]")
    out.append("")
    out.append("use super::api::Api;")
    out.append("use super::num::{Float32, Float64, Size64};")
    out.append("use super::PredefinedColorSpace;")
    out.append("")

    out.append("/// An IDL enum: its name, its values in IDL order, and each value's string.")
    out.append("pub trait IdlEnum: Copy + Eq + core::fmt::Debug + 'static {")
    out.append("    /// The IDL name of the enum.")
    out.append("    const IDL_NAME: &'static str;")
    out.append("    /// Every value, in IDL order.")
    out.append("    fn values() -> &'static [Self];")
    out.append("    /// The IDL string of a value.")
    out.append("    fn idl_str(self) -> &'static str;")
    out.append("    /// The position of a value in IDL order.")
    out.append("    fn index(self) -> usize;")
    out.append("}")
    out.append("")
    # enums
    for kind, name in model.order:
        if kind != "enum":
            continue
        e = model.enums[name]
        rn = rust_name(name)
        out.append("/// IDL `enum %s`." % name)
        out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
        out.append("pub enum %s {" % rn)
        for v in e["values"]:
            out.append('    /// `"%s"`' % v)
            out.append("    %s," % variant(v))
        out.append("}")
        out.append("")
        out.append("impl %s {" % rn)
        out.append("    /// Every value, in IDL order.")
        out.append("    pub const ALL: [%s; %d] = [%s];" % (rn, len(e["values"]), ", ".join("%s::%s" % (rn, variant(v)) for v in e["values"])))
        out.append("")
        out.append("    /// The IDL string.")
        out.append("    pub const fn as_str(self) -> &'static str {")
        out.append("        match self {")
        for v in e["values"]:
            out.append('            %s::%s => "%s",' % (rn, variant(v), v))
        out.append("        }")
        out.append("    }")
        out.append("")
        out.append("    /// The value with this IDL string, if any.")
        out.append("    pub fn from_idl(s: &str) -> Option<%s> {" % rn)
        out.append("        match s {")
        for v in e["values"]:
            out.append('            "%s" => Some(%s::%s),' % (v, rn, variant(v)))
        out.append("            _ => None,")
        out.append("        }")
        out.append("    }")
        out.append("}")
        out.append("")
        out.append("impl IdlEnum for %s {" % rn)
        out.append('    const IDL_NAME: &\'static str = "%s";' % name)
        out.append("    fn values() -> &'static [Self] {")
        out.append("        &Self::ALL")
        out.append("    }")
        out.append("    fn idl_str(self) -> &'static str {")
        out.append("        self.as_str()")
        out.append("    }")
        out.append("    fn index(self) -> usize {")
        out.append("        self as usize")
        out.append("    }")
        out.append("}")
        out.append("")

    # namespaces (flag constants)
    for kind, name in model.order:
        if kind != "namespace":
            continue
        ns = model.namespaces[name]
        rn = rust_name(name)
        out.append("/// IDL `namespace %s`: flag constants." % name)
        out.append("#[derive(Clone, Copy, Debug)]")
        out.append("pub struct %s;" % rn)
        out.append("")
        out.append("impl %s {" % rn)
        for c in ns["consts"]:
            out.append("    pub const %s: u32 = %s;" % (c["name"], c["value"]))
        out.append("    /// Every constant, by IDL name.")
        out.append("    pub const FLAGS: [(&'static str, u32); %d] = [%s];" % (len(ns["consts"]), ", ".join('("%s", %s)' % (c["name"], c["value"]) for c in ns["consts"])))
        out.append("}")
        out.append("")

    # union typedefs and anonymous unions
    unions = []
    for kind, name in model.order:
        if kind == "typedef" and model.typedefs[name]["type"].kind == "union" and name not in OPAQUE:
            unions.append((rust_name(name), model.typedefs[name]["type"], name))
    for key, rn in ANON_UNIONS.items():
        if rn == "ExternalVideo":
            continue
        t = Parser(tokenize(key)).type_()
        unions.append((rn, t, key))
    for rn, t, idlname in unions:
        generic = types.is_generic_type(t)
        out.append("/// IDL `%s`." % (idlname if idlname.startswith("(") else "typedef %s %s" % (t.text(), idlname)))
        out.append("#[derive(Clone, Debug)]")
        out.append("pub enum %s%s {" % (rn, types.params(generic)))
        for a in t.args:
            ra = types.resolve(a)
            if ra.kind == "sequence":
                vn = "Sequence"
            elif ra.kind == "named":
                vn = rust_name(ra.name)
            else:
                raise SystemExit("union arm %s" % a.text())
            out.append("    %s(%s)," % (vn, types.rust(a, ANON_UNIONS)))
        out.append("}")
        out.append("")

    # dictionaries
    for kind, name in model.order:
        if kind != "dict" or name in DOM_DICTS:
            continue
        rn = rust_name(name)
        generic = types.is_generic_dict(name)
        members = model.dict_members(name)
        out.append("/// IDL `dictionary %s`%s." % (name, (" : " + model.dicts[name]["base"]) if model.dicts[name]["base"] else ""))
        out.append("#[derive(Clone, Debug)]")
        out.append("pub struct %s%s {" % (rn, types.params(generic)))
        fields = []
        for mem in members:
            rt = types.rust(mem["type"], ANON_UNIONS)
            if mem["required"]:
                ft = rt
                how = "required"
            elif mem["default"] is not None:
                ft = rt
                how = "default %s" % mem["default"]
            else:
                ft = "Option<%s>" % rt
                how = "optional"
            fname = snake(mem["name"])
            fields.append((fname, ft, rt, mem, how))
            out.append("    /// `%s` (%s, %s)." % (mem["name"], mem["type"].text(), how))
            out.append("    pub %s: %s," % (fname, ft))
        if generic and not any("'a" in f[1] for f in fields):
            out.append("    pub _marker: core::marker::PhantomData<&'a A>,")
        out.append("}")
        out.append("")
        req = [f for f in fields if f[3]["required"]]
        out.append("impl%s %s%s {" % (types.params(generic), rn, types.args(generic)))
        out.append("    /// The dictionary with its required members and every other member at its IDL default.")
        out.append("    pub fn new(%s) -> Self {" % ", ".join("%s: %s" % (f[0], f[1]) for f in req))
        out.append("        %s {" % rn)
        for fname, ft, rt, mem, how in fields:
            if mem["required"]:
                out.append("            %s," % fname)
            elif mem["default"] is not None:
                out.append("            %s: %s," % (fname, rust_default(rt, mem["type"], mem["default"], model, types)))
            else:
                out.append("            %s: None," % fname)
        if generic and not any("'a" in f[1] for f in fields):
            out.append("            _marker: core::marker::PhantomData,")
        out.append("        }")
        out.append("    }")
        out.append("}")
        out.append("")

    # interface attribute sets read as plain data
    lim_names = [m["name"] for _, m in model.interface_members("GPUSupportedLimits") if m["kind"] == "attribute"]
    out.append("/// The attributes of IDL `interface GPUSupportedLimits`. `None`: the implementation does not expose the")
    out.append("/// attribute (a browser that predates it, or a native header without the field).")
    out.append("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]")
    out.append("pub struct SupportedLimits {")
    for _, m in model.interface_members("GPUSupportedLimits"):
        if m["kind"] != "attribute":
            continue
        rt = "u64" if m["type"].name == "unsigned long long" else "u32"
        out.append("    /// `%s`" % m["name"])
        out.append("    pub %s: Option<%s>," % (snake(m["name"]), rt))
    out.append("}")
    out.append("")
    out.append("impl SupportedLimits {")
    out.append("    /// The value of the limit with this IDL name, widened to `u64`; `None` if the name is not a limit or the")
    out.append("    /// implementation does not expose it.")
    out.append("    pub fn get(&self, name: &str) -> Option<u64> {")
    out.append("        match name {")
    for _, m in model.interface_members("GPUSupportedLimits"):
        if m["kind"] == "attribute":
            conv = "" if m["type"].name == "unsigned long long" else ".map(u64::from)"
            out.append('            "%s" => self.%s%s,' % (m["name"], snake(m["name"]), conv))
    out.append("            _ => None,")
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    /// Set the limit with this IDL name. Returns false if the name is not a limit or the value does not fit")
    out.append("    /// the limit's IDL type.")
    out.append("    pub fn set(&mut self, name: &str, value: Option<u64>) -> bool {")
    out.append("        match name {")
    for _, m in model.interface_members("GPUSupportedLimits"):
        if m["kind"] != "attribute":
            continue
        if m["type"].name == "unsigned long long":
            out.append('            "%s" => self.%s = value,' % (m["name"], snake(m["name"])))
        else:
            out.append('            "%s" => match value.map(u32::try_from).transpose() {' % m["name"])
            out.append("                Ok(v) => self.%s = v," % snake(m["name"]))
            out.append("                Err(_) => return false,")
            out.append("            },")
    out.append("            _ => return false,")
    out.append("        }")
    out.append("        true")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("/// IDL attribute names of `GPUSupportedLimits`, in IDL order.")
    out.append("pub const SUPPORTED_LIMITS: [&str; %d] = [%s];" % (len(lim_names), ", ".join('"%s"' % n for n in lim_names)))
    out.append("")

    out.append("/// The attributes of IDL `interface GPUAdapterInfo`. `None`: the implementation does not expose the attribute.")
    out.append("#[derive(Clone, Debug, Default, PartialEq, Eq)]")
    out.append("pub struct AdapterInfo {")
    for _, m in model.interface_members("GPUAdapterInfo"):
        if m["kind"] != "attribute":
            continue
        n = m["type"].name
        rt = {"DOMString": "String", "unsigned long": "u32", "boolean": "bool"}[n]
        out.append("    /// `%s`" % m["name"])
        out.append("    pub %s: Option<%s>," % (snake(m["name"]), rt))
    out.append("}")
    out.append("")

    # inventory of interface members; overloads of an operation are one member
    inv = []
    for iname in sorted(model.interfaces):
        for owner, m in model.interface_members(iname):
            key = (iname, m["name"], m["kind"])
            if m["kind"] != "const" and key not in inv:
                inv.append(key)
    out.append("/// Every member of every IDL interface (mixin members listed under each interface that includes them), as")
    out.append("/// (interface, member, kind). [`super::api::COVERAGE`] must account for each one.")
    out.append("pub const IDL_MEMBERS: [(&str, &str, &str); %d] = [" % len(inv))
    for key in inv:
        out.append('    ("%s", "%s", "%s"),' % key)
    out.append("];")
    out.append("")
    return "\n".join(out)


def emit_tables(model, limits_toml, formats_toml, format_lists, blend_rows, spec_ver):
    out = [HEADER.format(ver=spec_ver, tables="limits.toml and tables/formats.toml"), ""]
    out.append("//! Tables the binding layer reads at run time: the WebGPU limits and features of tables/limits.toml, the")
    out.append("//! feature each texture format requires (tables/formats.toml) and the feature each blend factor requires")
    out.append("//! (the GPUBlendFactor table of the specification).")
    out.append("")
    out.append("use super::idl::{BlendFactor, FeatureName, TextureFormat};")
    out.append("")
    out.append("/// How a limit compares: a `Maximum` is better when higher, an `Alignment` when lower.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    out.append("pub enum LimitClass {")
    out.append("    Maximum,")
    out.append("    Alignment,")
    out.append("}")
    out.append("")
    out.append("/// One row of the WebGPU limits table.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    out.append("pub struct Limit {")
    out.append("    /// The IDL attribute name.")
    out.append("    pub name: &'static str,")
    out.append("    /// `GPUSize32` or `GPUSize64`.")
    out.append("    pub size64: bool,")
    out.append("    pub class: LimitClass,")
    out.append("    /// The default limit (feature level \"core\").")
    out.append("    pub default: u64,")
    out.append("    /// The Compatibility Mode default limit (feature level \"compatibility\").")
    out.append("    pub compat_default: u64,")
    out.append("    /// The specification anchor of the row.")
    out.append("    pub cite: &'static str,")
    out.append("}")
    out.append("")
    lims = limits_toml["limit"]
    out.append("/// Every WebGPU limit, in the order of the specification's limits table.")
    out.append("pub const LIMITS: [Limit; %d] = [" % len(lims))
    for l in lims:
        cls = {"maximum": "Maximum", "alignment": "Alignment"}[l["class"]]
        out.append('    Limit { name: "%s", size64: %s, class: LimitClass::%s, default: %d, compat_default: %d, cite: "%s" },' % (
            l["name"], "true" if l["type"] == "GPUSize64" else "false", cls, l["default"], l["compat_default"], l["cite"][0]["ref"]))
    out.append("];")
    out.append("")
    out.append("/// One WebGPU feature.")
    out.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    out.append("pub struct Feature {")
    out.append("    pub name: FeatureName,")
    out.append("    /// Features this one requires directly (the Feature Dependencies table).")
    out.append("    pub requires: &'static [FeatureName],")
    out.append("    /// The WGSL enable-extension it gates, if any.")
    out.append("    pub wgsl_enable: Option<&'static str>,")
    out.append("}")
    out.append("")
    feats = limits_toml["feature"]
    out.append("/// Every WebGPU feature, in IDL order.")
    out.append("pub const FEATURES: [Feature; %d] = [" % len(feats))
    for f in feats:
        req = ", ".join("FeatureName::%s" % variant(r) for r in f.get("requires", []))
        we = 'Some("%s")' % f["wgsl_enable"] if f.get("wgsl_enable") else "None"
        out.append("    Feature { name: FeatureName::%s, requires: &[%s], wgsl_enable: %s }," % (variant(f["name"]), req, we))
    out.append("];")
    out.append("")
    # Format required features: the "Required Feature" column of the plain color formats table, the "Feature" column of
    # the packed formats table, and the "New GPUTextureFormat enum values" lists of the feature index. Where two of these
    # name a format, they must agree.
    required = {}

    def need(fmt, feat, where):
        if fmt in required and required[fmt] != feat:
            raise SystemExit("format %s requires %s (%s) and %s" % (fmt, required[fmt], where, feat))
        required[fmt] = feat

    for f in formats_toml["webgpu_texture_format"]:
        for asp in f["aspects"]:
            for col in ("Required Feature", "Feature"):
                v = asp.get(col, "(empty)")
                if v != "(empty)":
                    need(f["name"], v.strip('"'), "tables/formats.toml " + col)
    for feat, fmts in format_lists.items():
        for fmt in fmts:
            need(fmt, feat, "feature index")
    fmt_rows = [(f["name"], required.get(f["name"])) for f in formats_toml["webgpu_texture_format"]]
    fmt_enum = model.enums["GPUTextureFormat"]["values"]
    if sorted(n for n, _ in fmt_rows) != sorted(fmt_enum):
        raise SystemExit("tables/formats.toml formats differ from GPUTextureFormat")
    out.append("/// The feature a texture format requires (\"Validate texture format required features\"): the \"Required Feature\"")
    out.append("/// and \"Feature\" columns of tables/formats.toml and the \"New GPUTextureFormat enum values\" of the feature")
    out.append("/// index; `None`: none.")
    out.append("pub const fn format_required_feature(format: TextureFormat) -> Option<FeatureName> {")
    out.append("    match format {")
    for n, r in sorted(fmt_rows, key=lambda x: fmt_enum.index(x[0])):
        out.append("        TextureFormat::%s => %s," % (variant(n), ("Some(FeatureName::%s)" % variant(r)) if r else "None"))
    out.append("    }")
    out.append("}")
    out.append("")
    exts = [e["name"] for e in limits_toml["wgsl_language_extension"]]
    out.append("/// The WGSL language extensions (the values `wgslLanguageFeatures` may contain), from tables/limits.toml.")
    out.append("pub const WGSL_LANGUAGE_EXTENSIONS: [&str; %d] = [%s];" % (len(exts), ", ".join('"%s"' % e for e in exts)))
    out.append("")
    out.append("/// The feature a blend factor requires (the \"Feature\" column of the GPUBlendFactor table); `None`: none.")
    out.append("pub const fn blend_factor_required_feature(factor: BlendFactor) -> Option<FeatureName> {")
    out.append("    match factor {")
    for v, feat in blend_rows:
        out.append("        BlendFactor::%s => %s," % (variant(v), ("Some(FeatureName::%s)" % variant(feat)) if feat else "None"))
    out.append("    }")
    out.append("}")
    out.append("")
    return "\n".join(out)


def js_value(expr, t, types, model, depth=0):
    """Rust expression producing a JsValue for `expr` (a reference to a value of IDL type t)."""
    t = types.resolve(t)
    v = "v%d" % depth
    if t.kind == "named":
        n = t.name
        if n == "boolean":
            return "JsValue::from_bool(*%s)" % expr
        if n in ("unsigned short", "unsigned long", "long"):
            return "JsValue::from_f64(f64::from(*%s))" % expr
        if n == "unsigned long long":
            if ext_has(t, "EnforceRange"):
                return "JsValue::from_f64(%s.get() as f64)" % expr
            return "JsValue::from_f64(*%s as f64)" % expr
        if n == "float":
            return "JsValue::from_f64(f64::from(%s.get()))" % expr
        if n == "double":
            return "JsValue::from_f64(%s.get())" % expr
        if n in ("DOMString", "USVString"):
            return "JsValue::from_str(%s)" % expr
        if n == "PredefinedColorSpace":
            return "JsValue::from_str(%s.as_str())" % expr
        if n in OPAQUE:
            return "JsValue::from(%s.js())" % expr
        if n in INTERFACE_ASSOC:
            return "JsValue::from(%s.js())" % expr
        if n in model.enums:
            return "JsValue::from_str(%s.as_str())" % expr
        if n in model.dicts:
            return "JsValue::from(%s(%s))" % (dict_fn(n), expr)
        if n in model.typedefs:
            return "%s(%s)" % (union_fn(rust_name(n)), expr)
        raise SystemExit("js conversion for %s" % n)
    if t.kind == "sequence":
        inner = t.args[0]
        conv = js_value(v, inner, types, model, depth + 1)
        if inner.nullable:
            conv = "match %s { Some(%s) => %s, None => JsValue::NULL }" % (v, v, js_value(v, inner, types, model, depth + 1))
            return "{ let arr = Array::new(); for %s in %s.iter() { arr.push(&%s); } JsValue::from(arr) }" % (v, expr, conv)
        return "{ let arr = Array::new(); for %s in %s.iter() { arr.push(&%s); } JsValue::from(arr) }" % (v, expr, conv)
    if t.kind == "record":
        val = t.args[1]
        if val.kind == "union":
            rest = [a for a in val.args if not (a.kind == "named" and a.name == "undefined")]
            conv = "match %s { Some(%s) => %s, None => JsValue::UNDEFINED }" % (v, v, js_value(v, rest[0], types, model, depth + 1))
        else:
            conv = js_value(v, val, types, model, depth + 1)
        return "{ let rec = Object::new(); for (k, %s) in %s.iter() { set(&rec, k, &%s); } JsValue::from(rec) }" % (v, expr, conv)
    if t.kind == "union":
        if ANON_UNIONS.get(t.text()) == "ExternalVideo":
            return "JsValue::from(%s.js())" % expr
        return "%s(%s)" % (union_fn(ANON_UNIONS[t.text()]), expr)
    raise SystemExit("js conversion for %s" % t.text())


def dict_fn(idl_name):
    return "dict_" + snake(rust_name(idl_name)).replace("r#", "")


def union_fn(rust_union):
    return "union_" + snake(rust_union)


def emit_web(model, types, spec_ver):
    out = [HEADER.format(ver=spec_ver, tables="limits.toml"), ""]
    out.append("//! Every IDL dictionary and union as a JavaScript value, with the IDL member names. A member that is `None`")
    out.append("//! is left out (not present); every other member is set, defaulted ones to their value, which WebIDL treats")
    out.append("//! the same as a missing member that takes the default.")
    out.append("")
    out.append("#![allow(clippy::needless_borrow, clippy::redundant_closure, unused_variables)]")
    out.append("")
    out.append("use js_sys::{Array, Object};")
    out.append("use wasm_bindgen::JsValue;")
    out.append("")
    out.append("use super::Web;")
    out.append("use crate::gpu::idl::*;")
    out.append("")
    out.append("/// Set a property on a fresh plain object. `Reflect.set` on an ordinary extensible object without setters")
    out.append("/// cannot fail.")
    out.append("fn set(obj: &Object, key: &str, value: &JsValue) {")
    out.append("    let ok = js_sys::Reflect::set(obj, &JsValue::from_str(key), value);")
    out.append("    debug_assert!(matches!(ok, Ok(true)));")
    out.append("}")
    out.append("")
    for kind, name in model.order:
        if kind == "typedef" and model.typedefs[name]["type"].kind == "union" and name not in OPAQUE:
            emit_union_js(out, rust_name(name), model.typedefs[name]["type"], types, model)
    for key, rn in ANON_UNIONS.items():
        if rn == "ExternalVideo":
            continue
        emit_union_js(out, rn, Parser(tokenize(key)).type_(), types, model)
    for kind, name in model.order:
        if kind != "dict" or name in DOM_DICTS:
            continue
        generic = types.is_generic_dict(name)
        rn = rust_name(name) + ("<'_, Web>" if generic else "")
        out.append("/// `%s` as a JavaScript object." % name)
        out.append("pub(crate) fn %s(d: &%s) -> Object {" % (dict_fn(name), rn))
        out.append("    let o = Object::new();")
        for mem in model.dict_members(name):
            f = snake(mem["name"])
            if not mem["required"] and mem["default"] is None:
                out.append("    if let Some(v) = &d.%s {" % f)
                out.append('        set(&o, "%s", &%s);' % (mem["name"], js_value("v", mem["type"], types, model, 1)))
                out.append("    }")
            else:
                out.append('    set(&o, "%s", &%s);' % (mem["name"], js_value("(&d.%s)" % f, mem["type"], types, model, 1)))
        out.append("    o")
        out.append("}")
        out.append("")
    return "\n".join(out)


def emit_union_js(out, rn, t, types, model):
    generic = types.is_generic_type(t)
    out.append("/// `%s` as a JavaScript value." % rn)
    out.append("pub(crate) fn %s(u: &%s) -> JsValue {" % (union_fn(rn), rn + ("<'_, Web>" if generic else "")))
    out.append("    match u {")
    for a in t.args:
        ra = types.resolve(a)
        vn = "Sequence" if ra.kind == "sequence" else rust_name(ra.name)
        out.append("        %s::%s(x) => %s," % (rn, vn, js_value("x", a, types, model, 1)))
    out.append("    }")
    out.append("}")
    out.append("")


