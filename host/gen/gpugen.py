def rust_name(idl):
    """GPUBufferDescriptor -> BufferDescriptor."""
    if idl.startswith("GPU"):
        return idl[3:]
    return idl


def snake(name):
    s = re.sub(r"(\d+)D(?=[A-Z]|$)", r"_\1d", name)  # maxTextureDimension1D -> maxTextureDimension_1d
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = s.lower()
    if s in ("type", "ref", "move", "use", "loop", "match", "mod", "impl", "fn", "struct", "enum", "self"):
        s = "r#" + s
    return s


def variant(value):
    """An enum string value as a Rust variant: "rgba8unorm-srgb" -> Rgba8unormSrgb, "2d-array" -> D2Array."""
    parts = re.split(r"[-]", value)
    out = ""
    for i, p in enumerate(parts):
        if not p:
            continue
        if p[0].isdigit():
            if i == 0 and re.fullmatch(r"\d+d", p):
                out += "D" + p[:-1]
                continue
            if out and out[-1].isdigit():
                out += "_"
            out += p
        else:
            out += p[0].upper() + p[1:]
    if out[0].isdigit():
        out = "V" + out
    return out


def ext_has(t, attr):
    return any(e == attr or e.startswith(attr + "(") for e in t.ext)


class RustTypes:
    """Maps IDL types to Rust types and decides which dictionaries need `<'a, A: Api>`."""

    def __init__(self, model):
        self.m = model
        self._generic = {}

    def resolve(self, t):
        """Follow typedefs, carrying extended attributes."""
        seen = 0
        while t.kind == "named" and t.name in self.m.typedefs and t.name not in OPAQUE:
            inner = self.m.typedefs[t.name]["type"]
            if inner.kind == "union":
                return t  # union typedefs become their own Rust enum
            nt = Type(inner.kind, inner.name, inner.args, t.nullable or inner.nullable, inner.ext + t.ext)
            t = nt
            seen += 1
            if seen > 10:
                raise SystemExit("typedef loop")
        return t

    def is_generic_type(self, t, stack=()):
        t = self.resolve(t)
        if t.kind == "named":
            n = t.name
            if n in INTERFACE_ASSOC or n in OPAQUE:
                return True
            if n in self.m.dicts:
                return self.is_generic_dict(n, stack)
            if n in self.m.typedefs:
                return self.is_generic_type(self.m.typedefs[n]["type"], stack)
            return False
        return any(self.is_generic_type(a, stack) for a in t.args)

    def is_generic_dict(self, name, stack=()):
        if name in self._generic:
            return self._generic[name]
        if name in stack:
            return False
        g = any(self.is_generic_type(m["type"], stack + (name,)) for m in self.m.dict_members(name))
        self._generic[name] = g
        return g

    def is_generic_union(self, name):
        return self.is_generic_type(self.m.typedefs[name]["type"])

    def params(self, generic):
        return "<'a, A: Api>" if generic else ""

    def args(self, generic):
        return "<'a, A>" if generic else ""

    def rust(self, t, anon_unions):
        """Rust type for an IDL type in a dictionary member or union arm (non-null part)."""
        t = self.resolve(t)
        if t.kind == "named":
            n = t.name
            if n == "boolean":
                return "bool"
            if n == "unsigned short":
                return "u16"
            if n == "unsigned long":
                return "u32"
            if n == "long":
                return "i32"
            if n == "unsigned long long":
                return "Size64" if ext_has(t, "EnforceRange") else "u64"
            if n == "float":
                return "Float32"
            if n == "double":
                return "Float64"
            if n in ("DOMString", "USVString"):
                return "String"
            if n == "PredefinedColorSpace":
                return "PredefinedColorSpace"
            if n in OPAQUE:
                return "&'a A::ExternalVideoSource" if OPAQUE[n] == "external_video" else "&'a A::ExternalImageSource"
            if n in INTERFACE_ASSOC:
                return "&'a A::%s" % INTERFACE_ASSOC[n]
            if n in self.m.enums:
                return rust_name(n)
            if n in self.m.dicts:
                return rust_name(n) + self.args(self.is_generic_dict(n))
            if n in self.m.typedefs:  # union typedef
                return rust_name(n) + self.args(self.is_generic_union(n))
            raise SystemExit("IDL type %s has no Rust mapping" % n)
        if t.kind == "sequence":
            inner = t.args[0]
            r = self.rust(inner, anon_unions)
            if inner.nullable:
                r = "Option<%s>" % r
            return "Vec<%s>" % r
        if t.kind == "record":
            k = self.rust(t.args[0], anon_unions)
            v = t.args[1]
            if v.kind == "union" and any(a.kind == "named" and a.name == "undefined" for a in v.args):
                rest = [a for a in v.args if not (a.kind == "named" and a.name == "undefined")]
                if len(rest) != 1:
                    raise SystemExit("record value union %s" % v.text())
                return "Vec<(%s, Option<%s>)>" % (k, self.rust(rest[0], anon_unions))
            return "Vec<(%s, %s)>" % (k, self.rust(v, anon_unions))
        if t.kind == "union":
            key = t.text()
            opaque = {OPAQUE.get(a.name) for a in t.args if a.kind == "named"}
            if len(opaque) == 1 and None not in opaque and all(a.kind == "named" for a in t.args):
                # a union of host platform objects is one opaque host value
                return "&'a A::ExternalVideoSource" if opaque == {"external_video"} else "&'a A::ExternalImageSource"
            if key not in anon_unions:
                raise SystemExit("anonymous union %s has no name in ANON_UNIONS" % key)
            name = anon_unions[key]
            return name + self.args(self.is_generic_type(t))
        raise SystemExit("IDL type %s has no Rust mapping" % t.text())


# Anonymous unions in dictionaries, named here. Unions with "undefined" become Option.
ANON_UNIONS = {
    "(GPUPipelineLayout or GPUAutoLayoutMode)": "PipelineLayoutOrAuto",
    "(GPUTexture or GPUTextureView)": "TextureOrView",
    "(HTMLVideoElement or VideoFrame)": "ExternalVideo",
}


def rust_default(rt, t, value, model, types):
    """Rust expression for an IDL default value of IDL type t (Rust type rt)."""
    t = types.resolve(t)
    if value == "[]":
        return "Vec::new()"
    if value == "{}":
        if t.kind == "record":
            return "Vec::new()"
        if t.kind == "named" and t.name in model.dicts:
            return "%s::new()" % rust_name(t.name)
        if t.kind == "named" and t.name in model.typedefs:
            # union typedef default "{}" selects its dictionary arm with all defaults
            u = model.typedefs[t.name]["type"]
            for a in u.args:
                if a.kind == "named" and a.name in model.dicts:
                    return "%s::%s(%s::new())" % (rust_name(t.name), rust_name(a.name), rust_name(a.name))
        raise SystemExit("default {} for %s" % t.text())
    if value.startswith('"'):
        s = value.strip('"')
        if t.kind == "named" and t.name in model.enums:
            if s not in model.enums[t.name]["values"]:
                raise SystemExit("default %s not in enum %s" % (s, t.name))
            return "%s::%s" % (rust_name(t.name), variant(s))
        if rt == "String":
            return "String::from(%s)" % value
        if rt == "PredefinedColorSpace":
            return "PredefinedColorSpace::new(%s)" % value
        raise SystemExit("string default for %s" % rt)
    if value in ("true", "false"):
        return value
    num = int(value, 16) if value.lower().startswith("0x") else (float(value) if "." in value else int(value))
    if rt == "Size64":
        return "Size64::new_const(%d)" % num
    if rt == "Float32":
        return "Float32::new_const(%s_f32)" % (repr(float(num)))
    if rt == "Float64":
        return "Float64::new_const(%s_f64)" % (repr(float(num)))
    if rt in ("u16", "u32", "i32", "u64"):
        return "%s" % (hex(num) if value.lower().startswith("0x") else num)
    raise SystemExit("numeric default for %s" % rt)


