class Model:
    def __init__(self, defs):
        self.enums = {}
        self.dicts = {}
        self.typedefs = {}
        self.namespaces = {}
        self.interfaces = {}  # name -> {"base", "members": [...], "mixins": [...]}
        self.mixins = {}
        self.order = []
        for d in defs:
            k = d["def"]
            if k == "enum":
                self.enums[d["name"]] = d
                self.order.append(("enum", d["name"]))
            elif k == "dictionary":
                self.dicts[d["name"]] = d
                self.order.append(("dict", d["name"]))
            elif k == "typedef":
                self.typedefs[d["name"]] = d
                self.order.append(("typedef", d["name"]))
            elif k == "namespace":
                self.namespaces[d["name"]] = d
                self.order.append(("namespace", d["name"]))
            elif k == "mixin":
                self.mixins[d["name"]] = d
            elif k == "interface":
                self.interfaces[d["name"]] = {"base": d["base"], "members": list(d["members"]), "mixins": [], "ext": d["ext"]}
            elif k == "partial":
                self.interfaces.setdefault(d["name"], {"base": None, "members": [], "mixins": [], "ext": []})
                self.interfaces[d["name"]]["members"].extend(d["members"])
            elif k == "includes":
                self.interfaces.setdefault(d["target"], {"base": None, "members": [], "mixins": [], "ext": []})
                self.interfaces[d["target"]]["mixins"].append(d["mixin"])

    def interface_members(self, name):
        """(owner, member) of an interface, including members of the mixins it includes."""
        out = []
        it = self.interfaces[name]
        for m in it["members"]:
            out.append((name, m))
        for mx in it["mixins"]:
            if mx in self.mixins:
                for m in self.mixins[mx]["members"]:
                    out.append((mx, m))
        return out

    def dict_members(self, name):
        d = self.dicts[name]
        base = []
        if d["base"]:
            base = self.dict_members(d["base"])
        return base + [dict(m, owner=name) for m in d["members"]]


