//! Turns each test file of `host/tests` that replays reference cases into the root of a browser module.
//!
//! A test file is the root of its own crate under `cargo test`; here it is the root of an example crate
//! (`examples/<file>.rs` includes what this script writes), compiled for wasm32 with the `web` feature. The file's
//! text is kept as it is, with these changes only:
//!
//! - its inner attributes and inner doc comments are dropped (an included file cannot carry them; every test file
//!   has only `#![cfg(feature = "native")]`, which the example's `web` feature takes the place of);
//! - each `mod <name>;` names its file by absolute path, since the included text is not in `host/tests`;
//! - each `#[test]` attribute is replaced by `#[allow(dead_code)]` (which keeps the file's line numbers), and the
//!   function it marked is listed in `CASES`, in file order;
//! - `println!` and `eprintln!` write to the page's log (the test's output, as `cargo test -- --nocapture` shows it),
//!   through macros defined ahead of the text, which shadow the standard ones for the whole crate.
//!
//! The module's exports (`wm_case_count`, `wm_case_name`, `wm_run_case`) are written after the text; the page runs
//! one case per module instance (`webmetal_web_tests::run_case`).

use std::env;
use std::fs;
use std::path::PathBuf;

/// The test files whose cases the browser modules run: every file of `host/tests` that compares with the Metal
/// reference outputs.
const FILES: [&str; 9] = [
    "blit_exec",
    "compute_exec",
    "mem_buffers",
    "mem_exec",
    "mem_textures",
    "pipeline_exec",
    "render_cases",
    "tess_exec",
    "view_exec",
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let tests = manifest.parent().unwrap().join("tests");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", tests.display());
    for name in FILES {
        let path = tests.join(format!("{name}.rs"));
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let root = generate(name, &text, &tests);
        fs::write(out.join(format!("{name}.rs")), root).unwrap();
    }
}

fn generate(name: &str, text: &str, tests: &std::path::Path) -> String {
    let mut body = String::new();
    let mut cases = Vec::new();
    let mut marked = false;
    let mut preamble = true;
    for line in text.lines() {
        if preamble {
            let t = line.trim_start();
            if t.starts_with("//!") || t.starts_with("#![") {
                assert!(
                    !t.starts_with("#![") || t == "#![cfg(feature = \"native\")]",
                    "{name}.rs: inner attribute {t:?} has no place in the browser module"
                );
                body.push('\n');
                continue;
            }
            if !t.is_empty() {
                preamble = false;
            }
        }
        if line == "#[test]" {
            // An attribute in its place keeps the file's line numbers (panic locations) and the doc comment above it
            // attached to the function.
            marked = true;
            body.push_str("#[allow(dead_code)]\n");
            continue;
        }
        if marked {
            let f = line
                .strip_prefix("fn ")
                .and_then(|r| r.split('(').next())
                .unwrap_or_else(|| panic!("{name}.rs: #[test] is followed by {line:?}, not a function"));
            cases.push(f.to_string());
            marked = false;
        }
        if let Some(m) = line.strip_prefix("mod ").and_then(|r| r.strip_suffix(';')) {
            let dir = tests.join(m);
            let file = if dir.join("mod.rs").is_file() { dir.join("mod.rs") } else { tests.join(format!("{m}.rs")) };
            body.push_str(&format!("#[path = {:?}]\n{line}\n", file.display().to_string()));
            continue;
        }
        body.push_str(line);
        body.push('\n');
    }
    assert!(!cases.is_empty(), "{name}.rs has no test");
    let mut out = String::new();
    out.push_str(&format!("// Generated by host/web-tests/build.rs from host/tests/{name}.rs.\n\n"));
    for m in ["println", "eprintln"] {
        out.push_str(&format!(
            "#[allow(unused_macros)]\nmacro_rules! {m} {{\n    () => {{ ::webmetal_web_tests::log(\"\") }};\n    \
             ($($t:tt)*) => {{ ::webmetal_web_tests::log(&::std::format!($($t)*)) }};\n}}\n\n"
        ));
    }
    out.push_str(&body);
    out.push_str("\n/// The cases of this file, in file order.\nstatic CASES: &[(&str, fn())] = &[\n");
    for c in &cases {
        out.push_str(&format!("    ({c:?}, {c}),\n"));
    }
    out.push_str("];\n\n");
    out.push_str(
        "#[unsafe(no_mangle)]\npub extern \"C\" fn wm_case_count() -> u32 {\n    CASES.len() as u32\n}\n\n\
         #[unsafe(no_mangle)]\npub extern \"C\" fn wm_case_name(i: u32) -> u32 {\n    \
         ::webmetal_web_tests::case_name(CASES, i)\n}\n\n\
         #[unsafe(no_mangle)]\npub extern \"C\" fn wm_run_case(i: u32) -> u32 {\n    \
         ::webmetal_web_tests::run_case(CASES, i)\n}\n",
    );
    out
}
