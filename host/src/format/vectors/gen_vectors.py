#!/usr/bin/env python3
"""Generate the reference vectors of the ETC2/EAC and ASTC decoder tests from the Khronos VK-GL-CTS decoders.

The vectors are digests of the CTS framework's reference decodes (cts_oracle.cpp): the decoders the Vulkan and
OpenGL ES conformance tests compare implementations against.

Usage:
  gen_vectors.py --cts <VK-GL-CTS checkout> --build <scratch dir> [--full]

Writes astc_cts.txt and etc_cts.txt next to this file. With --full it also writes <scratch>/astc_full.txt and
<scratch>/etc_full.txt, every generated block with its digests, for the ignored tests
astc_matches_khronos_reference_file and etc_matches_khronos_reference_file.

ETC2/EAC blocks: every 64-bit pattern is a valid block, so the blocks are pseudo-random: the xorshift32 byte
generator of tests/reference/FORMAT.md ("Generated inputs") with one seed per kind. The vector is the count and the
digest of the per-block digests, which the test regenerates.

ASTC blocks: the CTS block test cases (generateBlockCaseTestData for each LDR BlockTestType), random valid LDR blocks
(generateRandomValidBlocks) and random blocks (generateRandomBlocks), per footprint. The vector file lists an evenly
spaced subset of each group with its digests.
"""

import argparse
import hashlib
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = ["framework/common/tcuAstcUtil.cpp", "framework/common/tcuCompressedTexture.cpp"]
C_SOURCES = ["framework/delibs/debase/deFloat16.c", "framework/delibs/debase/deRandom.c",
             "framework/delibs/debase/deMath.c"]
INCLUDES = ["framework/common", "framework/delibs/debase", "framework/delibs/decpp", "framework/delibs/deutil",
            "framework/delibs/depool", "framework/delibs/dethread", "framework/qphelper", "framework/referencerenderer"]

ETC_KINDS = [("rgb8", 8, 0x45544301), ("rgb8a1", 8, 0x45544302), ("rgba8", 16, 0x45544303),
             ("r11u", 8, 0x45544304), ("r11s", 8, 0x45544305)]
ETC_COUNT = 20000
ASTC_SUBSET = {"cases": 64, "valid": 40, "random": 16}


def xorshift_bytes(seed, n):
    s = seed or 0x9E3779B9
    out = bytearray()
    for _ in range(n):
        s ^= (s << 13) & 0xFFFFFFFF
        s ^= s >> 17
        s ^= (s << 5) & 0xFFFFFFFF
        out.append(s & 0xFF)
    return bytes(out)


def fnv64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def git_rev(cts):
    try:
        return subprocess.run(["git", "-C", cts, "rev-parse", "HEAD"], check=True, capture_output=True,
                              text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def build(cts, out):
    os.makedirs(out, exist_ok=True)
    inc = [f"-I{os.path.join(cts, i)}" for i in INCLUDES]
    objs = []
    for c in C_SOURCES:
        o = os.path.join(out, os.path.basename(c) + ".o")
        subprocess.run(["clang", "-c", "-O1", *inc, os.path.join(cts, c), "-o", o], check=True)
        objs.append(o)
    exe = os.path.join(out, "cts_oracle")
    subprocess.run(["clang++", "-std=c++17", "-O2", *inc, os.path.join(HERE, "cts_oracle.cpp"), *objs, "-o", exe],
                   check=True)
    return exe


def run(exe, mode, text):
    return subprocess.run([exe, mode], input=text, check=True, capture_output=True, text=True).stdout


def provenance(cts):
    lines = [f"# VK-GL-CTS revision {git_rev(cts)}"]
    for s in SOURCES:
        with open(os.path.join(cts, s), "rb") as fh:
            lines.append(f"# {s} sha256 {hashlib.sha256(fh.read()).hexdigest()}")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cts", required=True)
    ap.add_argument("--build", required=True)
    ap.add_argument("--full", action="store_true")
    a = ap.parse_args()
    exe = build(a.cts, a.build)
    prov = provenance(a.cts)

    # ETC2 / EAC.
    etc_lines = ["# Generated by host/src/format/vectors/gen_vectors.py. Do not edit by hand.",
                 "# <kind> <xorshift32 seed> <blocks> <FNV-1a 64 of the concatenated per-block digests, little-endian>",
                 *prov]
    full = []
    for kind, size, seed in ETC_KINDS:
        data = xorshift_bytes(seed, ETC_COUNT * size)
        blocks = [data[i:i + size].hex() for i in range(0, len(data), size)]
        out = run(exe, "etc-hash", "".join(f"{kind} {b}\n" for b in blocks)).split("\n")
        digests = [int(line.split(" ")[2], 16) for line in out if line]
        assert len(digests) == ETC_COUNT
        agg = fnv64(b"".join(d.to_bytes(8, "little") for d in digests))
        etc_lines.append(f"{kind} {seed:#010x} {ETC_COUNT} {agg:016x}")
        full.extend(line for line in out if line)
    with open(os.path.join(HERE, "etc_cts.txt"), "w") as fh:
        fh.write("\n".join(etc_lines) + "\n")
    if a.full:
        with open(os.path.join(a.build, "etc_full.txt"), "w") as fh:
            fh.write("\n".join(full) + "\n")

    # ASTC.
    gen = run(exe, "astc-gen", "").split("\n")
    hashed = run(exe, "astc-hash", "\n".join(gen) + "\n").split("\n")
    hashed = [h for h in hashed if h]
    if a.full:
        with open(os.path.join(a.build, "astc_full.txt"), "w") as fh:
            fh.write("\n".join(hashed) + "\n")
    by_fp = {}
    for line in hashed:
        w, h = line.split(" ")[:2]
        by_fp.setdefault((int(w), int(h)), []).append(line)
    astc_lines = ["# Generated by host/src/format/vectors/gen_vectors.py. Do not edit by hand.",
                  "# <w> <h> <block hex> <FNV-1a 64 of linear UNORM16 results> <FNV-1a 64 of sRGB-mode bytes>",
                  "# Per footprint: evenly spaced CTS block test cases, random valid LDR blocks, random blocks.",
                  *prov]
    for fp, lines in by_fp.items():
        # astc-gen emits the cases, then 256 random valid blocks, then 256 random blocks.
        cases, valid, rand = lines[:-512], lines[-512:-256], lines[-256:]
        for group, n in ((cases, ASTC_SUBSET["cases"]), (valid, ASTC_SUBSET["valid"]),
                         (rand, ASTC_SUBSET["random"])):
            step = max(1, len(group) // n)
            astc_lines.extend(group[::step][:n])
    with open(os.path.join(HERE, "astc_cts.txt"), "w") as fh:
        fh.write("\n".join(astc_lines) + "\n")
    print(f"ETC2/EAC: {len(ETC_KINDS)} kinds x {ETC_COUNT} blocks; ASTC: {len(hashed)} blocks, "
          f"{len(astc_lines) - 4 - len(prov) + 1} in the vector file", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
