#!/usr/bin/env python3
"""Render tables/refusals.md from gen/refusals.toml.

Usage: gen_refusals.py [--cache DIR] [--out PATH]
(--cache is accepted for symmetry with the other generators and is not used.)
"""

import argparse
import os
import sys
import tomllib

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.dirname(HERE)


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


def where(c, sources):
    if "sdk" in c:
        return "%s (%s)" % (c["sdk"], sources["sdk"]["version"])
    src = sources[c["src"]]
    ref = c.get("ref", "")
    if src["kind"] == "html" and ref:
        return "[%s %s](%s%s)" % (src["title"], ref, src["url"], ref)
    if ref:
        return "%s %s section %s" % (src["title"], src["version"], ref)
    return "%s (%s)" % (src["title"], src["url"])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache")
    ap.add_argument("--out", default=os.path.join(TABLES, "refusals.md"))
    a = ap.parse_args()
    with open(os.path.join(HERE, "refusals.toml"), "rb") as f:
        rows = tomllib.load(f)["refusal"]
    with open(os.path.join(TABLES, "sources.toml"), "rb") as f:
        sources = tomllib.load(f)["source"]
    out = [
        "<!-- Generated by tables/gen/gen_refusals.py from tables/gen/refusals.toml. Do not edit by hand. -->",
        "",
        "# Refusals",
        "",
        "Metal behavior that has no exact WebGPU or WGSL form on some or all hosts. A guest call or",
        "shader that needs one of these is refused loudly: the Metal error where Metal defines one,",
        "otherwise an unimplemented report naming the row, never a substitute. The device keeps",
        "reporting the A10X's capabilities; a row is removed only when an exact emulation lands with",
        "its tests. Each blocking clause is quoted and checked against the pinned text by",
        "`tables/check.py`.",
        "",
        "| Id | Area | Metal | Scope | Blocking clause | Source |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        src = "; ".join(where(c, sources) for c in r["cite"])
        out.append("| %s | %s | %s | %s | %s | %s |" % (
            r["id"], cell(r["area"]), cell(r["metal"]), cell(r["scope"]), cell(r["blocking"]), cell(src)))
    out.append("")
    with open(a.out, "w") as f:
        f.write("\n".join(out))
    print("wrote %s (%d refusals)" % (a.out, len(rows)))


if __name__ == "__main__":
    main()
