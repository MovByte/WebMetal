// Measurement pvrtc-mac: does this Mac's Metal device create and read PVRTC textures?
//
// For each PVRTC pixel format, an 8x8 texture is created with shader-read usage and filled
// with a fixed byte pattern (block i byte j = (i * 37 + j * 11) & 0xff); a compute kernel
// reads every texel with read() and the decoded RGBA values are printed. A format the
// device does not support gives a nil texture, which is recorded as such. The output is
// TOML on stdout.
//
// Build and run: xcrun swiftc -O pvrtc_mac.swift -o pvrtc_mac && ./pvrtc_mac > pvrtc_mac.toml

import Foundation
import Metal

let kernelSource = """
#include <metal_stdlib>
using namespace metal;
kernel void readall(texture2d<float, access::read> t [[texture(0)]],
                    device float4* o [[buffer(0)]],
                    uint2 p [[thread_position_in_grid]]) {
    o[p.y * 8 + p.x] = t.read(p);
}
"""

func q(_ s: String) -> String { "\"" + s.replacingOccurrences(of: "\"", with: "\\\"") + "\"" }

guard let device = MTLCreateSystemDefaultDevice() else {
    FileHandle.standardError.write("no Metal device\n".data(using: .utf8)!)
    exit(1)
}
var out = "# Generated by tables/measure/pvrtc_mac.swift. Do not edit by hand.\n\n[meta]\n"
out += "id = \"pvrtc-mac\"\n"
out += "script = \"tables/measure/pvrtc_mac.swift\"\n"
out += "device = \(q(device.name))\n"
let os = ProcessInfo.processInfo.operatingSystemVersionString
out += "host = \(q("macOS " + os))\n"
var families: [String] = []
for (name, fam) in [("apple1", MTLGPUFamily.apple1), ("apple2", .apple2), ("apple3", .apple3), ("apple4", .apple4),
                    ("apple5", .apple5), ("apple6", .apple6), ("apple7", .apple7), ("apple8", .apple8),
                    ("apple9", .apple9), ("mac2", .mac2)] where device.supportsFamily(fam) {
    families.append(name)
}
out += "supported_families = [" + families.map(q).joined(separator: ", ") + "]\n"

let library = try device.makeLibrary(source: kernelSource, options: nil)
let pipeline = try device.makeComputePipelineState(function: library.makeFunction(name: "readall")!)
let queue = device.makeCommandQueue()!

let formats: [(String, MTLPixelFormat, Int)] = [
    ("MTLPixelFormatPVRTC_RGB_2BPP", .pvrtc_rgb_2bpp, 2), ("MTLPixelFormatPVRTC_RGB_4BPP", .pvrtc_rgb_4bpp, 4),
    ("MTLPixelFormatPVRTC_RGBA_2BPP", .pvrtc_rgba_2bpp, 2), ("MTLPixelFormatPVRTC_RGBA_4BPP", .pvrtc_rgba_4bpp, 4),
]
for (name, format, bpp) in formats {
    out += "\n[[case]]\nid = \(q(name))\n"
    let desc = MTLTextureDescriptor.texture2DDescriptor(pixelFormat: format, width: 8, height: 8, mipmapped: false)
    desc.usage = .shaderRead
    desc.storageMode = .shared
    guard let tex = device.makeTexture(descriptor: desc) else {
        out += "texture = \"nil\"\n"
        continue
    }
    out += "texture = \"created\"\n"
    // PVRTC 4bpp uses 4x4-texel 8-byte blocks, 2bpp 8x4-texel 8-byte blocks; the minimum
    // image is 2x2 blocks, so an 8x8 image is (8/4)x(8/4) or (8/8)x(8/4) blocks, at least 4.
    let blocks = max(4, bpp == 4 ? 4 : 2)
    var bytes = [UInt8](repeating: 0, count: blocks * 8)
    for i in 0..<blocks { for j in 0..<8 { bytes[i * 8 + j] = UInt8((i * 37 + j * 11) & 0xff) } }
    tex.replace(region: MTLRegionMake2D(0, 0, 8, 8), mipmapLevel: 0, withBytes: bytes, bytesPerRow: 0)
    let outBuf = device.makeBuffer(length: 64 * 16, options: .storageModeShared)!
    let cb = queue.makeCommandBuffer()!
    let enc = cb.makeComputeCommandEncoder()!
    enc.setComputePipelineState(pipeline)
    enc.setTexture(tex, index: 0)
    enc.setBuffer(outBuf, offset: 0, index: 0)
    enc.dispatchThreadgroups(MTLSize(width: 1, height: 1, depth: 1), threadsPerThreadgroup: MTLSize(width: 8, height: 8, depth: 1))
    enc.endEncoding()
    cb.commit()
    cb.waitUntilCompleted()
    out += "status = \(q(String(describing: cb.status.rawValue)))\n"
    if let err = cb.error { out += "error = \(q(err.localizedDescription))\n" }
    let p = outBuf.contents().bindMemory(to: Float.self, capacity: 256)
    var vals: [String] = []
    for i in 0..<256 { vals.append(String(format: "%.9g", p[i])) }
    out += "texels_rgba = [" + vals.joined(separator: ", ") + "]\n"
}
print(out, terminator: "")
