"""Render a collected profile as TOML, checking method agreement on the way.

Every value line ends with a comment that states its provenance: `A <symbol> <address>` for
the primary method (the target's own code under emulation), then the verdict of the second
method: `B1 agrees` (host Metal.framework), `B2 agrees` (LLVM decode of the driver getter), or
the reason the value is single-method. Pixel-format records name their function once in the
table header; each field line states its own verdict.
"""

import math
import struct

from . import sdk
from .build import (DRIVER_CLASSES, INFO_WORDS, NAMED_FLAG_BITS, BuildError, ret_kind, static_value)
from .target import CACHE_UUID, DEVICE_CLASS, PIXEL_FORMAT_RANGE, struct_fields

SDK_ENUMS = {
    'supportsFamily:': 'MTLGPUFamily', 'supportsFeatureSet:': 'MTLFeatureSet',
    'deviceSupportsFeatureSet:': 'MTLFeatureSet', 'deviceOrFeatureProfileSupportsFeatureSet:': 'MTLFeatureSet',
    'supportsPrimitiveType:': 'MTLPrimitiveType', 'supportsCounterSampling:': 'MTLCounterSamplingPoint',
    'sparseTileSizeInBytesForSparsePageSize:': 'MTLSparsePageSize',
    'minimumLinearTextureAlignmentForPixelFormat:': 'MTLPixelFormat',
    'minLinearTextureAlignmentForPixelFormat:': 'MTLPixelFormat',
    'minimumTextureBufferAlignmentForPixelFormat:': 'MTLPixelFormat',
}
# Disagreements between the target's framework build and the host's, each with the target
# instruction that shows the target's answer is the target's own: (address, word, text).
EXPLAINED = {
    'minimumLinearTextureAlignmentForPixelFormat:': (
        0x187a7eee0, 0x52800800,
        'host build differs: the target returns the immediate 0x40 (mov w0, #0x40 at 0x187a7eee0); '
        'the host build sends minLinearTextureAlignmentForPixelFormat: instead'),
}


class HexInt(int):
    """An integer written as a hexadecimal TOML literal (flag words)."""


def toml_value(value):
    if isinstance(value, HexInt):
        return f'0x{int(value):08x}'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, float):
        if math.isnan(value) or math.isinf(value):
            raise BuildError('non-finite float in profile')
        text = repr(value)
        return text if ('.' in text or 'e' in text) else text + '.0'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (list, tuple)):
        return '[' + ', '.join(toml_value(v) for v in value) + ']'
    raise BuildError(f'value {value!r} is not a number or boolean')


def key(name):
    return name if all(c.isalnum() or c in '_-' for c in name) else '"' + name.replace('"', '\\"') + '"'


def same(a, b):
    if isinstance(a, float) or isinstance(b, float):
        return float(a) == float(b)
    if isinstance(a, (list, tuple)) and isinstance(b, (list, tuple)):
        return len(a) == len(b) and all(same(x, y) for x, y in zip(a, b))
    return a == b


class Writer:
    def __init__(self):
        self.lines = []
        self.counts = {'values': 0, 'two_method': 0, 'single_method': 0}

    def section(self, name, comment=None):
        if self.lines:
            self.lines.append('')
        if comment:
            for line in comment:
                self.lines.append('# ' + line if line else '#')
        self.lines.append(f'[{name}]')

    def value(self, name, value, provenance, verified):
        self.counts['values'] += 1
        self.counts['two_method' if verified else 'single_method'] += 1
        self.lines.append(f'{key(name)} = {toml_value(value)}  # {provenance}')

    def text(self):
        return '\n'.join(self.lines) + '\n'


def host_verdict(entry, a_value):
    """'agrees', or the reason the host cannot confirm the value; raises on disagreement."""
    if entry is None:
        return 'B1 not asked'
    if 'unimplemented' in entry:
        return 'B1 unreachable: the host framework does not implement the query'
    if 'trapped' in entry:
        return 'B1 unreachable: the host framework calls ' + ', '.join(sorted(set(entry['trapped'])))
    if same(entry['value'], a_value):
        return 'B1 agrees'
    return None


def render(profile):
    a, host, static = profile.a, profile.b['host'], profile.b['static']
    product, build = host['os']
    w = Writer()
    w.lines += [
        f'# Metal device profile of {DEVICE_CLASS}: iPadOS 17.7.11 (21H461), iPad7,1 (J120AP), A10X.',
        '# Generated by UniXNU scripts/audit-target-metal-profile.py from the user\'s own 21H461 root;',
        f'# shared cache UUID {CACHE_UUID.upper()}. Do not edit by hand.',
        '#',
        '# Values are numbers and booleans. The comment after each value is its provenance:',
        '#   A <symbol> <address>  the target\'s own code executed in emulation (method A)',
        f'#   B1 ...                the host Metal.framework (macOS {product} {build}) running the same',
        '#                         query for a device that returns the A10X driver answers',
        '#   B2 ...                the driver getter\'s body decoded with LLVM\'s disassembler',
        '#   B3 ...                MSL constexpr samplers compiled by the host Metal compiler',
        '# "agrees" means the second method gave the same value; otherwise the line states why the',
        '# value is single-method. A value the methods disagree on is never written.',
        f'# Public names come from the iPhoneOS {sdk.sdk_version()} SDK headers.',
    ]

    # -- driver and framework getters ---------------------------------------------------------
    for title, table in (('getters', a['getters']), ('driver_getters', a['driver_getters'])):
        comment = (['Zero-argument MTLDevice and MTLDeviceSPI queries of the device.'] if title == 'getters' else
                   ['Zero-argument methods of the driver classes that are not in the protocols.'])
        w.section(title, comment)
        for selector, (outcome, types, _) in sorted(table.items()):
            if outcome.kind != 'value':
                continue
            where = a['where'].get(selector) or where_driver(profile, selector)
            verdicts = []
            hv = host_verdict(host['getters'].get(selector), outcome.value) if selector in host['getters'] else None
            if hv is None and selector in host['getters']:
                raise BuildError(f'{selector}: A {outcome.value} B1 {host["getters"][selector]}')
            if hv:
                verdicts.append(hv)
            if selector in static:
                kind, decoded = static[selector]
                if kind == 'value':
                    sv = static_value(decoded, ret_kind(types))
                    if sv is None:
                        verdicts.append('B2 unreachable: decoded registers do not hold the return value')
                    elif same(sv, outcome.value):
                        verdicts.append('B2 agrees')
                    else:
                        raise BuildError(f'{selector}: A {outcome.value} B2 {sv}')
                else:
                    verdicts.append('B2 unreachable: ' + decoded)
            if not verdicts:
                verdicts.append('B1 not asked: driver method; B2 not asked')
            verified = any(v.endswith('agrees') for v in verdicts)
            value = outcome.value
            if isinstance(value, list) and len(value) == 3:
                value = list(value)
            w.value(selector, value, f'A {where}; ' + '; '.join(verdicts), verified)

    w.section('runtime', ['Queries whose answer is device state the kernel or the process supplies, not a',
                          'constant of the binaries: the instance variable read is named. true = listed.'])
    for title, table in (('getters', a['getters']), ('driver_getters', a['driver_getters'])):
        for selector, (outcome, types, _) in sorted(table.items()):
            if outcome.kind == 'runtime':
                w.value(selector, True, f'A {a["where"].get(selector) or where_driver(profile, selector)}: '
                                        f'{outcome.detail}', False)
    outcome, texture = a['heap_texture']
    if outcome.kind != 'runtime':
        raise BuildError(f'heapTextureSizeAndAlignWithDescriptor: {outcome}')
    settings = ', '.join(f'{s} {v}' for s, v in texture)
    w.value('heapTextureSizeAndAlignWithDescriptor:', True,
            f'A {profile.target.where("heapTextureSizeAndAlignWithDescriptor:")} for a descriptor with {settings}: '
            f'{outcome.detail} (the AGX texture layout depends on the device object built from the kernel)', False)
    w.section('unimplemented', ['Protocol methods no class of the device chain implements (respondsToSelector: NO).'])
    for selector, (outcome, types, _) in sorted(a['getters'].items()):
        if outcome.kind == 'unimplemented':
            w.value(selector, True, f'A no IMP in {DEVICE_CLASS}, AGXA10FamilyDevice, IOGPUMetalDevice, '
                                    '_MTLDevice, NSObject; B1 not applicable', False)
    w.section('not_evaluated', ['Protocol queries that are not device capabilities or have no defined argument domain.'])
    for selector, reason in sorted(a['skipped'].items()):
        w.value(selector, True, reason, False)
    errors = [(s, o) for s, (o, _, _) in {**a['getters'], **a['driver_getters']}.items() if o.kind in ('error', 'failure')]
    if errors:
        raise BuildError(f'getters ended in errors: {errors[:5]}')

    # -- parameterized ------------------------------------------------------------------------
    for selector, (table, types) in a['parameterized'].items():
        names = {}
        if selector in SDK_ENUMS:
            for name, value in sdk.enum_constants(SDK_ENUMS[selector]):
                names.setdefault(value, name)
        host_table = host['parameterized'].get(selector)
        driver_side = a['definer'][selector] in DRIVER_CLASSES
        w.section(f'queries.{key(selector)}', [f'A {a["where"][selector]}, one call per argument.'])
        for arg, outcome in sorted(table.items()):
            if outcome.kind != 'value':
                continue
            label = names.get(arg, f'not declared in {SDK_ENUMS[selector]}') if selector in SDK_ENUMS else 'integer argument'
            if driver_side:
                kind, decoded = profile.b['static_parameterized'][selector][arg]
                if kind != 'value':
                    verdict, verified = f'B1 not applicable: driver method; B2 unreachable: {decoded}', False
                else:
                    sv = static_value(decoded, ret_kind(types))
                    if sv is None:
                        verdict, verified = 'B2 unreachable: decoded registers do not hold the return value', False
                    elif same(sv, outcome.value):
                        verdict, verified = 'B2 agrees', True
                    else:
                        raise BuildError(f'{selector}({arg}): A {outcome.value} B2 {sv}')
            else:
                entry = host_table.get(str(arg)) if host_table and 'unimplemented' not in host_table else host_table
                verdict = host_verdict(entry, outcome.value)
                if verdict is None:
                    reason = explained(profile, selector)
                    if reason is None:
                        raise BuildError(f'{selector}({arg}): A {outcome.value} B1 {entry}')
                    verdict = f'B1 {entry["value"]}: {reason}'
                verified = verdict.endswith('agrees')
            w.value(str(arg), outcome.value, f'{label}; A; {verdict}', verified)
        failures = [(arg, o) for arg, o in sorted(table.items()) if o.kind != 'value']
        if failures:
            w.section(f'query_failures.{key(selector)}',
                      ['Arguments for which the target reports a validation failure; the value is the',
                       'line number Metal passes to its failure report.'])
            for arg, outcome in failures:
                if outcome.kind != 'failure':
                    raise BuildError(f'{selector}({arg}): {outcome}')
                label = (names.get(arg, f'not declared in {SDK_ENUMS[selector]}') if selector in SDK_ENUMS
                         else 'integer argument')
                w.value(str(arg), outcome.value, f'{label}; A {outcome.detail}; '
                                                 'B1 not asked: the failure path is not run in the host process', False)

    # -- limits -------------------------------------------------------------------------------
    host_limits = parse_host_limits(host['limits'])
    w.section('limits', ['_MTLDevice._limits after MTLAddDevice\'s sequence (initLimits, initFeatureQueries,',
                         f'initWorkarounds). A {profile.target.where("initLimits")}, '
                         'emulated; field names from the ivar\'s type encoding, offsets in the instance.'])
    for name, kind, offset, outcome in a['limits']:
        if outcome.kind != 'value':
            continue
        hv = host_limits.get(name)
        if hv is None:
            verdict = 'B1 unreachable: the host _limits has no such field'
        elif same(hv, outcome.value):
            verdict = 'B1 agrees'
        else:
            raise BuildError(f'limit {name}: A {outcome.value} B1 {hv}')
        w.value(name, outcome.value, f'+{offset:#x}; A -[_MTLDevice initLimits]; {verdict}', verdict.endswith('agrees'))
    w.section('limits_runtime', ['_limits fields that are copies of kernel-supplied state.'])
    for name, kind, offset, outcome in a['limits']:
        if outcome.kind != 'value':
            w.value(name, True, f'+{offset:#x}; A {outcome.detail}', False)

    # -- inputs and assumptions ---------------------------------------------------------------
    w.section('kernel_inputs', ['Driver methods the framework calls during MTLAddDevice\'s sequence whose answer is',
                                'kernel-supplied state. They were answered with two different sentinel values; any',
                                'result that changed is listed as runtime above. true = listed.'])
    for selector, info in sorted(a['inputs'].items()):
        w.value(selector, True, f'A {info["at"]} reads {info["read"]}', False)
    w.section('initial_state', ['Instance variables MTLAddDevice\'s sequence reads before it writes them, with the',
                                'value they hold after initWithAcceleratorPort: and the evidence for it.'])
    for name, evidence in a['initial_state'].items():
        w.value(name, 0, evidence, False)
    w.section('dispatch', ['Method lists that message dispatch in method A could miss.'])
    count, images = a['categories']
    w.value('foreign_categories', count, f'A __objc_catlist and __objc_catlist2 of all {images} images scanned for '
                                         f'categories on {DEVICE_CLASS}, AGXA10FamilyDevice, IOGPUMetalDevice, _MTLDevice',
            False)
    w.section('program_sdk', ['Linked-on-or-after checks met on the way, answered for a program built with the iOS 17',
                              'SDK: key = dyld_build_version_t as 0xPLATFORM_VERSION, value = answer.'])
    for platform, version, answer in a['sdk_queries']:
        w.value(f'0x{platform:08x}_{version:08x}', answer, 'A dyld_program_sdk_at_least, modelled', False)
    if a['environment']:
        raise BuildError(f'environment variables consulted: {a["environment"]}')

    render_pixel_formats(w, profile)
    render_samples_and_heap(w, profile)
    render_sampler_state(w, profile)
    return w


def where_driver(profile, selector):
    target = profile.target
    cls, method = target.method(selector)
    return f'-[{cls.name} {selector}] {method.imp:#x}'


def explained(profile, selector):
    if selector not in EXPLAINED:
        return None
    address, word, text = EXPLAINED[selector]
    actual = profile.target.cache.u32(address)
    if actual != word:
        raise BuildError(f'explanation for {selector} no longer matches the target at {address:#x}')
    return text


def parse_host_limits(limits):
    raw = bytes.fromhex(limits['bytes'])
    out, at = {}, 0
    for name, kind in struct_fields(limits['encoding']):
        size = 8 if kind == 'Q' else 4
        at = (at + size - 1) // size * size
        out[name] = struct.unpack('<f', raw[at:at + 4])[0] if kind == 'f' else int.from_bytes(raw[at:at + size], 'little')
        at += size
    return out


def info_fields(record):
    out = {}
    for offset, size in INFO_WORDS:
        out[f'word_{offset:02x}'] = int.from_bytes(record[offset:offset + size], 'little')
    return out


def render_pixel_formats(w, profile):
    a, host = profile.a, profile.b['host']
    names = {}
    for name, value in sdk.enum_constants('MTLPixelFormat'):
        names.setdefault(value, name)
    function = a['pixel_format_function']
    invalid_name = a['pixel_formats'][0].value[:8]
    known, private, unknown = [], [], []
    for fmt in PIXEL_FORMAT_RANGE:
        record = a['pixel_formats'][fmt].value
        if record[:8] == invalid_name:
            if any(record[8:]):
                raise BuildError(f'pixel format {fmt}: invalid name with nonzero fields')
            unknown.append(fmt)
            continue
        known.append(fmt)
        if fmt not in names:
            private.append(fmt)
    w.section('pixel_format_list', [f'MTLPixelFormat values {PIXEL_FORMAT_RANGE.start}..{PIXEL_FORMAT_RANGE.stop - 1} '
                                    f'given to MTLPixelFormatGetInfoForDevice {function:#x} (A, emulated).',
                                    'known: a record other than the invalid one; private: known but not in the SDK enum.'])
    w.value('known', known, f'A MTLPixelFormatGetInfoForDevice {function:#x}; compared with the SDK enum', False)
    w.value('private', private, f'A MTLPixelFormatGetInfoForDevice {function:#x}; compared with the SDK enum', False)
    lines = [
        'MTLPixelFormatInfo (56 bytes) of each known format, as MTLPixelFormatGetInfoForDevice',
        f'{function:#x} fills it for this device (A, emulated). word_XX is the little-endian field at byte',
        'offset XX; byte 0 is a pointer to the format name and is omitted. Named booleans decode flag',
        'bits of word_08 whose meaning the target binary establishes:',
    ]
    for bit, (name, source) in sorted(NAMED_FLAG_BITS.items()):
        lines.append(f'  bit {bit:2d} {name}: {source}')
    lines.append('Each field line states the B1 verdict for that field.')
    w.section('pixel_formats', lines)
    for fmt in known:
        record = a['pixel_formats'][fmt].value
        entry = host['pixel_formats'].get(str(fmt))
        host_record = None
        if entry and 'value' in entry:
            host_record = bytes(8) + bytes.fromhex(entry['value'])
        label = names.get(fmt, 'private')
        w.lines.append('')
        w.lines.append(f'[pixel_formats.{fmt}]  # {label}; A MTLPixelFormatGetInfoForDevice {function:#x}')
        fields = info_fields(record)
        host_fields = info_fields(host_record) if host_record else None
        for name, value in fields.items():
            if host_fields is None:
                verdict = ('B1 unreachable: the host framework calls ' + ', '.join(entry['trapped'])) if entry else 'B1 not asked'
            elif host_fields[name] == value:
                verdict = 'B1 agrees'
            else:
                verdict = f'B1 {host_fields[name]:#x}: the host framework build computes a different value'
            w.value(name, HexInt(value) if name == 'word_08' else value, f'A; {verdict}', verdict == 'B1 agrees')
            if name == 'word_08':
                for bit, (flag, _) in sorted(NAMED_FLAG_BITS.items()):
                    mine = bool(value >> bit & 1)
                    if host_fields is None:
                        fv = verdict
                    elif bool(host_fields['word_08'] >> bit & 1) == mine:
                        fv = 'B1 agrees'
                    else:
                        fv = 'B1 differs: the host framework build computes a different value'
                    w.value(flag, mine, f'A bit {bit} of word_08; {fv}', fv == 'B1 agrees')


def render_samples_and_heap(w, profile):
    a, host, static = profile.a, profile.b['host'], profile.b['static']
    where = a['where']['getDefaultSamplePositions:count:']
    w.section('sample_positions', [f'A {where}: positions written for count N as [x0, y0, x1, y1, ...].'])
    failures = []
    for count, outcome in sorted(a['sample_positions'].items()):
        entry = host['sample_positions'].get(str(count))
        if outcome.kind == 'value':
            verdict = host_verdict(entry, outcome.value)
            if verdict is None:
                raise BuildError(f'sample positions {count}: A {outcome.value} B1 {entry}')
            w.value(f'count_{count}', outcome.value, f'A {where}; {verdict}', verdict.endswith('agrees'))
        else:
            failures.append((count, outcome, entry))
    w.section('sample_position_failures', ['Counts the device does not support: the target reports a failure (value = line).'])
    for count, outcome, entry in failures:
        if outcome.kind != 'failure':
            raise BuildError(f'sample positions {count}: {outcome}')
        agree = entry is not None and entry.get('unsupported')
        w.value(f'count_{count}', outcome.value,
                f'A {outcome.detail}; ' + ('B1 agrees: supportsTextureSampleCount: is NO on the host framework too'
                                           if agree else f'B1 {entry}'), bool(agree))
    selector = 'heapBufferSizeAndAlignWithLength:options:'
    cases = a['heap_buffer']
    sizes = {k: o.value for k, o in cases.items()}
    if any(o.kind != 'value' for o in cases.values()):
        raise BuildError('heap buffer size query failed')
    equal_length = all(size == length for (length, _), (size, _) in sizes.items())
    aligns = {align for _, align in sizes.values()}
    if len(aligns) != 1:
        raise BuildError(f'heap buffer alignment varies: {aligns}')
    align = aligns.pop()
    kind, decoded = static[selector]
    b2 = (kind == 'value' and decoded.get('x0') == ('arg', 0) and decoded.get('x1') == align)
    w.section('heap', [f'A {where_driver(profile, selector)} over {len(cases)} (length, options) pairs:',
                       'lengths 0..2^63-1 at page and alignment edges, every CPU cache mode, storage mode',
                       'and hazard tracking mode.'])
    verdict = 'B2 agrees: returns its length argument and the immediate alignment' if b2 else 'B2 unreachable'
    w.value('buffer_size_is_length', equal_length, f'A; {verdict}', b2)
    w.value('buffer_alignment', align, f'A; {verdict}', b2)


SAMPLER_ENUMS = {'sAddressMode': 'MTLSamplerAddressMode', 'tAddressMode': 'MTLSamplerAddressMode',
                 'rAddressMode': 'MTLSamplerAddressMode', 'magFilter': 'MTLSamplerMinMagFilter',
                 'minFilter': 'MTLSamplerMinMagFilter', 'mipFilter': 'MTLSamplerMipFilter',
                 'compareFunction': 'MTLCompareFunction', 'borderColor': 'MTLSamplerBorderColor'}


def render_sampler_state(w, profile):
    layout, check = profile.a['sampler'], profile.b['sampler']
    decoder, caller = layout['decoder'], layout['caller']
    compiler = f'{check["version"]}, air64-apple-ios17.0'
    w.section('sampler_state', [
        'The 64-bit air.sampler_state word of an MSL constexpr sampler, as the target decodes it into an',
        f'MTLSamplerDescriptor: A setDescriptorFromBitmask {decoder:#x} (called by',
        f'_MTLCreateConstantSamplerDescriptorsFromBitmasks {caller:#x}) executed on {layout["calls"]} words: one per',
        'bit, every code of every field, and random words with valid codes (fields compose independently).',
        f'B3: {check["cases"]} constexpr samplers compiled by {compiler}, decoded with these tables and',
        'compared with the descriptor values their MSL arguments name.',
        'Each field: offset/width in bits, code_N = property value for code N (SDK enumerator value).'])
    # TOML integers are signed 64-bit, so bit sets are written as lists of bit numbers.
    w.value('required_bit', 63,
            f'A a word without bit 63 fails (line {layout["missing_valid_failure"]}); B3 agrees: every compiled word sets it', True)
    lines = sorted(set(layout['reserved_failures'].values()))
    w.value('reserved_bits', [b for b in range(64) if layout['reserved_bits'] >> b & 1],
            f'A a word with any of these bits fails (line {", ".join(map(str, lines))}); B3 agrees: no compiled word sets them', True)
    w.value('unused_bits', [b for b in range(64) if layout['unused_bits'] >> b & 1], 'A bits no field reads; B3 not applicable', False)
    border_code, zero_code = check['border_lowering']
    for name, field in layout['fields'].items():
        enum = dict((v, n) for n, v in reversed(sdk.enum_constants(SAMPLER_ENUMS[name]))) if name in SAMPLER_ENUMS else {}
        w.lines.append('')
        w.lines.append(f'[sampler_state.{name}]  # A setDescriptorFromBitmask {decoder:#x}; '
                       f'bits {field["offset"]}..{field["offset"] + field["width"] - 1}')
        placed = any(n == name for n, _ in check['confirmed']) or any(n == name for n, _ in check['lods'])
        verdict = 'B3 agrees' if placed else 'B3 unreachable'
        w.value('offset', field['offset'], f'A; {verdict}', placed)
        w.value('width', field['width'], f'A; {verdict}', placed)
        if field.get('encoding') == 'binary16':
            values = sorted(code for n, code in check['lods'] if n == name)
            w.value('binary16', True, f'A {field["codes_checked"]} codes decode as IEEE binary16 (NaN payloads '
                                      f'not compared); B3 agrees on codes {", ".join(f"{c:#06x}" for c in values)}', True)
            continue
        failures = {}
        for code, value in enumerate(field['values']):
            if value is None:
                failures[code] = field['failures'][code]
                continue
            label = enum.get(value, 'no SDK enumerator') if name in SAMPLER_ENUMS else ''
            if (name, code) in check['confirmed']:
                verdict, ok = 'B3 agrees', True
            elif name.endswith('AddressMode') and value == dict(sdk.enum_constants('MTLSamplerAddressMode')).get(
                    'MTLSamplerAddressModeClampToBorderColor'):
                verdict, ok = (f'B3 unreachable: the compiler writes code {border_code} (the clamp_to_zero code '
                               f'{zero_code}) for clamp_to_border'), False
            else:
                verdict, ok = 'B3 unreachable: no compiled case names the value of this code', False
            value_out = value
            w.value(f'code_{code}', value_out, (label + '; ' if label else '') + f'A; {verdict}', ok)
        if failures:
            w.value('failing_codes', sorted(failures),
                    f'A each fails (line {", ".join(map(str, sorted(set(failures.values()))))}); B3 not applicable', False)
