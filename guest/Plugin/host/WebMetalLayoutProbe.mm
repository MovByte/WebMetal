// Records the layouts of this Mac's Metal.framework base classes for the macOS test shim: for every base class and
// selector of the 21H461 tables (guest/Generated/WebMetalTargetSurface.h), what the running classes have. Writes a C++
// source that defines webmetal::kExpectedLayouts with them; the shim's guard then refuses a Metal.framework that
// differs from the one it was built on. Selectors are looked up as the guard looks them up (FrameworkMethod). The
// runtime answers only the word-aligned instance size (class_getInstanceSize), which is recorded as the size: the guard
// compares sizes rounded up to a word, and an aligned size rounds to itself.
//
//     WebMetalLayoutProbe <output.mm>

#import <Foundation/Foundation.h>
#import <Metal/Metal.h>
#import <objc/runtime.h>

#include "../../Generated/WebMetalTargetSurface.h"

#include <cstdio>
#include <string>

using namespace webmetal;

static std::string literal(const char *text)
{
    if (!text)
        return "nullptr";
    std::string out = "\"";
    for (const char *p = text; *p; p++) {
        if (*p == '"' || *p == '\\')
            out += '\\';
        out += *p;
    }
    return out + "\"";
}

int main(int argc, char **argv)
{
    @autoreleasepool {
        if (argc != 2) {
            fprintf(stderr, "usage: %s output.mm\n", argv[0]);
            return 2;
        }
        // Loads Metal.framework's classes as a Metal client sees them.
        (void)MTLCopyAllDevices();
        NSOperatingSystemVersion v = NSProcessInfo.processInfo.operatingSystemVersion;
        std::string source = "macOS " + std::to_string(v.majorVersion) + "." + std::to_string(v.minorVersion) + "." +
                             std::to_string(v.patchVersion) + " (" +
                             NSProcessInfo.processInfo.operatingSystemVersionString.UTF8String + ")";
        std::string out = "// Generated by guest/Plugin/host/WebMetalLayoutProbe.mm on " + source + ". Do not edit.\n\n"
                          "#import \"WebMetalSurface.h\"\n\nnamespace webmetal {\n\nnamespace {\n\n";
        std::string table;
        for (const BaseLayout &base : target::kBases) {
            Class cls = objc_getClass(base.name);
            if (!cls) {
                fprintf(stderr, "no class %s on this Mac\n", base.name);
                return 1;
            }
            const std::string id = std::string("k") + base.name;
            unsigned count = 0;
            Ivar *ivars = class_copyIvarList(cls, &count);
            out += "const BaseIvar " + id + "Ivars[] = {\n";
            for (unsigned i = 0; i < count; i++)
                out += "    {" + literal(ivar_getName(ivars[i])) + ", " + std::to_string(ivar_getOffset(ivars[i])) + ", " +
                       literal(ivar_getTypeEncoding(ivars[i])) + "},\n";
            if (!count)
                out += "    {nullptr, 0, nullptr},  // none; the count below is 0\n";
            free(ivars);
            out += "};\nconst BaseSelector " + id + "Selectors[] = {\n";
            for (size_t i = 0; i < base.selectorCount; i++) {
                const BaseSelector &s = base.selectors[i];
                if (!s.name)
                    continue;
                Method method = FrameworkMethod(cls, s.kind, s.name);
                out += std::string("    {SelectorKind::") + (s.kind == SelectorKind::Class ? "Class" : "Instance") +
                       ", " + literal(s.name) + ", " + literal(method ? method_getTypeEncoding(method) : nullptr) +
                       "},\n";
            }
            if (!base.selectorCount)
                out += "    {SelectorKind::Instance, nullptr, nullptr},  // none; the count below is 0\n";
            out += "};\n\n";
            Class superclass = class_getSuperclass(cls);
            table += "    {" + literal(base.name) + ", " + literal(superclass ? class_getName(superclass) : "") + ", " +
                     std::to_string(class_getInstanceSize(cls)) + ", " + id + "Ivars, " + std::to_string(count) + ", " +
                     id + "Selectors, " + std::to_string(base.selectorCount) + "},\n";
        }
        out += "const BaseLayout kHostBases[] = {\n" + table + "};\n\n}  // namespace\n\n" +
               "const LayoutSet kExpectedLayouts = {" + literal(source.c_str()) +
               ", kHostBases, sizeof kHostBases / sizeof *kHostBases};\n\n}  // namespace webmetal\n";
        FILE *file = fopen(argv[1], "w");
        if (!file || fputs(out.c_str(), file) < 0 || fclose(file) != 0) {
            perror(argv[1]);
            return 1;
        }
        printf("recorded %zu base classes of %s\n", sizeof target::kBases / sizeof *target::kBases, source.c_str());
    }
    return 0;
}
