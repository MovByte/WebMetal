WMREF_CASE(blitBufferToTexture2D, "blit.buffer-to-texture-2d", "blit.copy",
           "Buffer to 2D texture sub-region with a row pitch that is not a multiple of 256 and an offset")
{
    // RGBA8Unorm (4-byte pixels) and R16Uint (2-byte pixels); the source
    // offset is a multiple of the pixel size as the documentation requires.
    struct { MTLPixelFormat format; NSString *name; NSUInteger bpp; } formats[] = {
        {MTLPixelFormatRGBA8Unorm, @"RGBA8Unorm", 4},
        {MTLPixelFormatR16Uint, @"R16Uint", 2},
    };
    for (int f = 0; f < 2; f++) {
        NSUInteger bpp = formats[f].bpp;
        id<MTLTexture> t = WMMakeTexture(c, MTLTextureType2D, formats[f].format, 16, 12, 1, 1, 1);
        WMFillTexture(c, t, bpp, 200 + f);
        NSUInteger rowPitch = 7 * bpp + bpp * 3, offset = bpp * 5;
        NSUInteger length = offset + rowPitch * 5;
        NSMutableData *bytes = [NSMutableData dataWithLength:length];
        WMPattern(bytes.mutableBytes, length, 210 + f);
        id<MTLBuffer> source = [c bufferWithBytes:bytes.bytes length:length];
        [c blit:^(id<MTLBlitCommandEncoder> e) {
            [e copyFromBuffer:source sourceOffset:offset sourceBytesPerRow:rowPitch sourceBytesPerImage:0
                   sourceSize:MTLSizeMake(7, 5, 1) toTexture:t destinationSlice:0 destinationLevel:0
            destinationOrigin:MTLOriginMake(3, 2, 0)];
        }];
        NSData *after = [c readTexture:t level:0 slice:0 bytesPerRow:16 * bpp];
        [c data:[NSString stringWithFormat:@"%@.texture", formats[f].name] elem:WMElemU8 bytes:after.bytes
          length:after.length layout:WMLayout(formats[f].name, 16, 12, 1, 16 * bpp) rule:WMExact()];
    }
}

WMREF_CASE(blitBufferToTexture3D, "blit.buffer-to-texture-3d", "blit.copy",
           "Buffer to 3D texture region with an image pitch, and back with different pitches")
{
    id<MTLTexture> t = WMMakeTexture(c, MTLTextureType3D, MTLPixelFormatRGBA8Uint, 8, 6, 5, 1, 1);
    WMFillTexture(c, t, 4, 300);
    NSUInteger rowPitch = 6 * 4, imagePitch = rowPitch * 4 + 8, offset = 16;
    NSUInteger length = offset + imagePitch * 3;
    NSMutableData *bytes = [NSMutableData dataWithLength:length];
    WMPattern(bytes.mutableBytes, length, 301);
    id<MTLBuffer> source = [c bufferWithBytes:bytes.bytes length:length];
    id<MTLBuffer> region = [c buffer:5 * 4 * 2 * 4 + 64];
    memset(region.contents, 0x77, region.length);
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromBuffer:source sourceOffset:offset sourceBytesPerRow:rowPitch sourceBytesPerImage:imagePitch
               sourceSize:MTLSizeMake(5, 3, 3) toTexture:t destinationSlice:0 destinationLevel:0
        destinationOrigin:MTLOriginMake(2, 1, 1)];
        // Read a 5x4x2 region back at an offset with tight pitches.
        [e copyFromTexture:t sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(1, 1, 2)
                sourceSize:MTLSizeMake(5, 4, 2) toBuffer:region destinationOffset:64
    destinationBytesPerRow:5 * 4 destinationBytesPerImage:5 * 4 * 4];
    }];
    NSData *after = [c readTexture:t level:0 slice:0 bytesPerRow:8 * 4];
    [c data:@"texture" elem:WMElemU8 bytes:after.bytes length:after.length
     layout:WMLayout(@"RGBA8Uint", 8, 6, 5, 32) rule:WMExact()];
    [c data:@"region-readback" elem:WMElemU8 bytes:region.contents length:region.length rule:WMExact()];
}

WMREF_CASE(blitArrayCubeLevels, "blit.slices-and-levels", "blit.copy",
           "Buffer/texture copies addressing 2D-array slices, cube faces and mip levels")
{
    id<MTLTexture> array = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatR32Uint, 8, 8, 1, 3, 3);
    id<MTLTexture> cube = WMMakeTexture(c, MTLTextureTypeCube, MTLPixelFormatRG16Uint, 4, 4, 1, 1, 2);
    WMFillTexture(c, array, 4, 400);
    WMFillTexture(c, cube, 4, 500);
    uint32_t words[4 * 4];
    WMPattern(words, sizeof words, 401);
    id<MTLBuffer> source = [c bufferWithBytes:words length:sizeof words];
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        // Level 1 of slice 2 is 4x4; write its lower-right 3x2 corner.
        [e copyFromBuffer:source sourceOffset:4 sourceBytesPerRow:16 sourceBytesPerImage:0
               sourceSize:MTLSizeMake(3, 2, 1) toTexture:array destinationSlice:2 destinationLevel:1
        destinationOrigin:MTLOriginMake(1, 2, 0)];
        // Face 4 (+Z) of the cube, level 1 (2x2).
        [e copyFromBuffer:source sourceOffset:32 sourceBytesPerRow:8 sourceBytesPerImage:0
               sourceSize:MTLSizeMake(2, 2, 1) toTexture:cube destinationSlice:4 destinationLevel:1
        destinationOrigin:MTLOriginMake(0, 0, 0)];
    }];
    for (NSUInteger slice = 0; slice < 3; slice++)
        for (NSUInteger level = 0; level < 3; level++) {
            NSUInteger w = 8 >> level;
            NSData *bytes = [c readTexture:array level:level slice:slice bytesPerRow:w * 4];
            [c data:[NSString stringWithFormat:@"array.slice%lu.level%lu", (unsigned long)slice, (unsigned long)level]
               elem:WMElemU32 bytes:bytes.bytes length:bytes.length layout:WMLayout(@"R32Uint", w, w, 1, w * 4)
               rule:WMExact()];
        }
    for (NSUInteger face = 0; face < 6; face++)
        for (NSUInteger level = 0; level < 2; level++) {
            NSUInteger w = 4 >> level;
            NSData *bytes = [c readTexture:cube level:level slice:face bytesPerRow:w * 4];
            [c data:[NSString stringWithFormat:@"cube.face%lu.level%lu", (unsigned long)face, (unsigned long)level]
               elem:WMElemU16 bytes:bytes.bytes length:bytes.length layout:WMLayout(@"RG16Uint", w, w, 1, w * 4)
               rule:WMExact()];
        }
}

WMREF_CASE(blitTextureToBuffer, "blit.texture-to-buffer", "blit.copy",
           "Texture to buffer copies of 1D, 2D and 1D-array regions at offsets with padded pitches")
{
    id<MTLTexture> t1d = WMMakeTexture(c, MTLTextureType1D, MTLPixelFormatRGBA16Uint, 32, 1, 1, 1, 1);
    id<MTLTexture> t2d = WMMakeTexture(c, MTLTextureType2D, MTLPixelFormatR8Uint, 13, 9, 1, 1, 1);
    id<MTLTexture> t1da = WMMakeTexture(c, MTLTextureType1DArray, MTLPixelFormatR32Float, 16, 1, 1, 4, 1);
    WMFillTexture(c, t1d, 8, 600);
    WMFillTexture(c, t2d, 1, 601);
    // R32Float data is copied as bytes; blits do not convert.
    WMFillTexture(c, t1da, 4, 602);
    id<MTLBuffer> out = [c buffer:1024];
    memset(out.contents, 0xcd, out.length);
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromTexture:t1d sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(5, 0, 0)
                sourceSize:MTLSizeMake(20, 1, 1) toBuffer:out destinationOffset:8
    destinationBytesPerRow:0 destinationBytesPerImage:0];
        [e copyFromTexture:t2d sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(2, 3, 0)
                sourceSize:MTLSizeMake(9, 5, 1) toBuffer:out destinationOffset:200
    destinationBytesPerRow:11 destinationBytesPerImage:0];
        [e copyFromTexture:t1da sourceSlice:3 sourceLevel:0 sourceOrigin:MTLOriginMake(4, 0, 0)
                sourceSize:MTLSizeMake(10, 1, 1) toBuffer:out destinationOffset:512
    destinationBytesPerRow:0 destinationBytesPerImage:0];
    }];
