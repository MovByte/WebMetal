    // needs to be a multiple of 4, but can be any value in iOS and tvOS"
    // (the same for destinationOffset and size).
    [c require:@"platform.unaligned-buffer-copies-valid" value:!TARGET_OS_OSX];
    uint8_t source[128];
    WMPattern(source, sizeof source, 102);
    id<MTLBuffer> a = [c bufferWithBytes:source length:sizeof source];
    id<MTLBuffer> b = [c buffer:128];
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromBuffer:a sourceOffset:3 toBuffer:b destinationOffset:7 size:61];
    }];
    [c data:@"destination" elem:WMElemU8 bytes:b.contents length:b.length rule:WMExact()];
}

WMREF_CASE(blitCopyBufferUnalignedMacOS, "blit.copy-buffer-unaligned-macos", "validation.blit",
           "Buffer copy with unaligned offsets on macOS, where the documentation requires multiples of 4")
{
    [c require:@"platform.macos" value:TARGET_OS_OSX];
    uint8_t source[128];
    WMPattern(source, sizeof source, 102);
    id<MTLBuffer> a = [c bufferWithBytes:source length:sizeof source];
    id<MTLBuffer> b = [c buffer:128];
    id<MTLCommandBuffer> commandBuffer = [c commandBuffer];
    id<MTLBlitCommandEncoder> e = [commandBuffer blitCommandEncoder];
    [c step:@"encode-unaligned-copy"];
    [e copyFromBuffer:a sourceOffset:3 toBuffer:b destinationOffset:7 size:61];
    [c step:@"end-encoding"];
    [e endEncoding];
    [commandBuffer commit];
    [commandBuffer waitUntilCompleted];
    [c value:@"status" i64:commandBuffer.status rule:WMNone(@"misuse on macOS: the result is not defined")];
    [c data:@"destination" elem:WMElemU8 bytes:b.contents length:b.length
        rule:WMNone(@"misuse on macOS: the result is not defined")];
}

