}

WMREF_CASE(blitTextureToTextureRegion, "blit.texture-to-texture-region", "blit.copy",
           "Region copies between textures across slices, levels and origins, including 3D and one texture to itself")
{
    id<MTLTexture> a = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatRGBA8Unorm, 16, 16, 1, 2, 2);
    id<MTLTexture> b = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatRGBA8Unorm, 8, 8, 1, 3, 1);
    id<MTLTexture> v = WMMakeTexture(c, MTLTextureType3D, MTLPixelFormatR16Float, 6, 6, 6, 1, 1);
    id<MTLTexture> w = WMMakeTexture(c, MTLTextureType3D, MTLPixelFormatR16Float, 4, 4, 4, 1, 1);
    WMFillTexture(c, a, 4, 700);
    WMFillTexture(c, b, 4, 701);
    WMFillTexture(c, v, 2, 702);
    WMFillTexture(c, w, 2, 703);
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        // Slice 1 level 1 of a (8x8) into slice 2 of b at (2,3).
        [e copyFromTexture:a sourceSlice:1 sourceLevel:1 sourceOrigin:MTLOriginMake(1, 1, 0)
                sourceSize:MTLSizeMake(5, 4, 1) toTexture:b destinationSlice:2 destinationLevel:0
         destinationOrigin:MTLOriginMake(2, 3, 0)];
        // 3D sub-volume.
        [e copyFromTexture:v sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(1, 2, 3)
                sourceSize:MTLSizeMake(3, 2, 2) toTexture:w destinationSlice:0 destinationLevel:0
         destinationOrigin:MTLOriginMake(0, 1, 1)];
        // Within one texture, between slices.
        [e copyFromTexture:b sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(0, 0, 0)
                sourceSize:MTLSizeMake(4, 4, 1) toTexture:b destinationSlice:1 destinationLevel:0
         destinationOrigin:MTLOriginMake(4, 4, 0)];
    }];
    for (NSUInteger slice = 0; slice < 3; slice++) {
        NSData *bytes = [c readTexture:b level:0 slice:slice bytesPerRow:8 * 4];
        [c data:[NSString stringWithFormat:@"b.slice%lu", (unsigned long)slice] elem:WMElemU8 bytes:bytes.bytes
          length:bytes.length layout:WMLayout(@"RGBA8Unorm", 8, 8, 1, 32) rule:WMExact()];
    }
    NSData *volume = [c readTexture:w level:0 slice:0 bytesPerRow:4 * 2];
    [c data:@"w" elem:WMElemU16 bytes:volume.bytes length:volume.length layout:WMLayout(@"R16Float", 4, 4, 4, 8)
       rule:WMExact()];
}

WMREF_CASE(blitTextureToTextureWhole, "blit.texture-to-texture-whole", "blit.copy",
           "copyFromTexture:toTexture: and the sliceCount/levelCount form")
{
    id<MTLTexture> a = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatRG8Uint, 8, 4, 1, 3, 3);
    id<MTLTexture> b = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatRG8Uint, 8, 4, 1, 3, 3);
    id<MTLTexture> d = WMMakeTexture(c, MTLTextureType2DArray, MTLPixelFormatRG8Uint, 4, 2, 1, 4, 2);
    WMFillTexture(c, a, 2, 800);
    WMFillTexture(c, b, 2, 801);
    WMFillTexture(c, d, 2, 802);
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromTexture:a toTexture:b];
        // a's level 1 (4x2) matches d's level 0: copy two slices, two levels.
        [e copyFromTexture:a sourceSlice:1 sourceLevel:1 toTexture:d destinationSlice:2 destinationLevel:0
                sliceCount:2 levelCount:2];
    }];
    for (NSUInteger slice = 0; slice < 3; slice++)
        for (NSUInteger level = 0; level < 3; level++) {
            NSUInteger width = 8 >> level, height = MAX((NSUInteger)1, (NSUInteger)4 >> level);
            NSData *bytes = [c readTexture:b level:level slice:slice bytesPerRow:width * 2];
            [c data:[NSString stringWithFormat:@"b.slice%lu.level%lu", (unsigned long)slice, (unsigned long)level]
               elem:WMElemU8 bytes:bytes.bytes length:bytes.length
             layout:WMLayout(@"RG8Uint", width, height, 1, width * 2) rule:WMExact()];
        }
    for (NSUInteger slice = 0; slice < 4; slice++)
        for (NSUInteger level = 0; level < 2; level++) {
            NSUInteger width = 4 >> level, height = 2 >> level;
            NSData *bytes = [c readTexture:d level:level slice:slice bytesPerRow:width * 2];
            [c data:[NSString stringWithFormat:@"d.slice%lu.level%lu", (unsigned long)slice, (unsigned long)level]
               elem:WMElemU8 bytes:bytes.bytes length:bytes.length
             layout:WMLayout(@"RG8Uint", width, height, 1, width * 2) rule:WMExact()];
        }
}

WMREF_CASE(blitFormatMismatch, "blit.texture-to-texture-format-mismatch", "validation.blit",
           "Texture copy between different pixel formats, which the documentation does not allow")
{
    // copyFromTexture:...: "The pixel format is the same as sourceTexture."
    id<MTLTexture> a = WMMakeTexture(c, MTLTextureType2D, MTLPixelFormatRGBA8Unorm, 4, 4, 1, 1, 1);
    id<MTLTexture> b = WMMakeTexture(c, MTLTextureType2D, MTLPixelFormatRGBA8Uint, 4, 4, 1, 1, 1);
    WMFillTexture(c, a, 4, 900);
    WMFillTexture(c, b, 4, 901);
    id<MTLCommandBuffer> commandBuffer = [c commandBuffer];
    id<MTLBlitCommandEncoder> e = [commandBuffer blitCommandEncoder];
    [c step:@"encode-mismatched-copy"];
    [e copyFromTexture:a sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(0, 0, 0)
            sourceSize:MTLSizeMake(4, 4, 1) toTexture:b destinationSlice:0 destinationLevel:0
     destinationOrigin:MTLOriginMake(0, 0, 0)];
    [c step:@"end-encoding"];
    [e endEncoding];
    [commandBuffer commit];
    [commandBuffer waitUntilCompleted];
    [c value:@"status" i64:commandBuffer.status rule:WMNone(@"misuse: the result is not defined")];
}

WMREF_CASE(blitMultisampleCopy, "blit.texture-to-texture-multisample", "blit.copy",
           "Whole-texture copy between 4-sample textures, read back per sample")
{
    [c require:@"texture-sample-count-4" value:[c.device supportsTextureSampleCount:4]];
    MTLTextureDescriptor *d = [MTLTextureDescriptor new];
    d.textureType = MTLTextureType2DMultisample;
    d.pixelFormat = MTLPixelFormatR32Uint;
    d.width = 4;
    d.height = 4;
    d.sampleCount = 4;
    d.storageMode = MTLStorageModePrivate;
    d.usage = MTLTextureUsageRenderTarget | MTLTextureUsageShaderRead;
    id<MTLTexture> a = [c texture:d], b = [c texture:d];
    // Clear the source to a known value through a render pass load action.
    MTLRenderPassDescriptor *pass = [MTLRenderPassDescriptor renderPassDescriptor];
    pass.colorAttachments[0].texture = a;
    pass.colorAttachments[0].loadAction = MTLLoadActionClear;
    pass.colorAttachments[0].storeAction = MTLStoreActionStore;
    pass.colorAttachments[0].clearColor = MTLClearColorMake(305419896, 0, 0, 0);
    [c render:pass body:^(id<MTLRenderCommandEncoder> e) {}];
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromTexture:a toTexture:b];
    }];
    id<MTLComputePipelineState> pipeline = [c computePipeline:@"blit_read_ms"];
    id<MTLBuffer> out = [c buffer:4 * 4 * 4 * sizeof(uint32_t)];
    [c compute:^(id<MTLComputeCommandEncoder> e) {
        [e setComputePipelineState:pipeline];
        [e setTexture:b atIndex:0];
        [e setBuffer:out offset:0 atIndex:0];
        [e dispatchThreadgroups:MTLSizeMake(1, 1, 1) threadsPerThreadgroup:MTLSizeMake(4, 4, 1)];
    }];
    // 305419896 = 0x12345678 is exactly representable in double and in R32Uint.
    [c data:@"samples" elem:WMElemU32 bytes:out.contents length:out.length rule:WMExact()];
}

WMREF_CASE(blitOptimizeContents, "blit.optimize-contents", "blit.misc",
           "optimizeContentsForGPUAccess and ForCPUAccess leave texture contents unchanged")
{
    MTLTextureDescriptor *d = [MTLTextureDescriptor texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Uint
                                                                                 width:8 height:8 mipmapped:YES];
    d.storageMode = MTLStorageModeShared;
    d.usage = MTLTextureUsageShaderRead;
    id<MTLTexture> t = [c texture:d];
    for (NSUInteger level = 0; level < t.mipmapLevelCount; level++) {
        NSUInteger w = 8 >> level;
        NSMutableData *bytes = [NSMutableData dataWithLength:w * w * 4];
        WMPattern(bytes.mutableBytes, bytes.length, 1000 + (uint32_t)level);
        [t replaceRegion:MTLRegionMake2D(0, 0, w, w) mipmapLevel:level withBytes:bytes.bytes bytesPerRow:w * 4];
    }
    NSData *before = [c readTexture:t level:0 slice:0 bytesPerRow:32];
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e optimizeContentsForGPUAccess:t];
        [e optimizeContentsForCPUAccess:t slice:0 level:1];
        [e optimizeContentsForGPUAccess:t slice:0 level:2];
        [e optimizeContentsForCPUAccess:t];
    }];
    for (NSUInteger level = 0; level < t.mipmapLevelCount; level++) {
        NSUInteger w = 8 >> level;
        NSMutableData *bytes = [NSMutableData dataWithLength:w * w * 4];
        [t getBytes:bytes.mutableBytes bytesPerRow:w * 4 fromRegion:MTLRegionMake2D(0, 0, w, w) mipmapLevel:level];
        [c data:[NSString stringWithFormat:@"level%lu", (unsigned long)level] elem:WMElemU8 bytes:bytes.bytes
          length:bytes.length layout:WMLayout(@"RGBA8Uint", w, w, 1, w * 4) rule:WMExact()];
    }
    NSData *after = [c readTexture:t level:0 slice:0 bytesPerRow:32];
    [c value:@"level0-unchanged" boolean:[before isEqualToData:after] rule:WMExact()];
}
