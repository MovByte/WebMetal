// Blit encoder cases: buffer copies and fills, buffer/texture copies with
// pitches, offsets, slices, levels and depth, texture/texture copies in
// every public form, and content-optimization hints.

#import "WMRefCase.h"
#include <TargetConditionals.h>

static NSDictionary *WMLayout(NSString *format, NSUInteger width, NSUInteger height, NSUInteger depth,
                              NSUInteger bytesPerRow) {
    return @{@"format": format, @"width": @(width), @"height": @(height), @"depth": @(depth),
             @"bytes_per_row": @(bytesPerRow), @"bytes_per_image": @(bytesPerRow * height)};
}

static id<MTLTexture> WMMakeTexture(WMCase *c, MTLTextureType type, MTLPixelFormat format, NSUInteger width,
                                    NSUInteger height, NSUInteger depth, NSUInteger arrayLength,
                                    NSUInteger levels) {
    MTLTextureDescriptor *d = [MTLTextureDescriptor new];
    d.textureType = type;
    d.pixelFormat = format;
    d.width = width;
    d.height = height;
    d.depth = depth;
    d.arrayLength = arrayLength;
    d.mipmapLevelCount = levels;
    d.storageMode = MTLStorageModePrivate;
    d.usage = MTLTextureUsageShaderRead;
    return [c texture:d];
}

// Fills every level and slice of a texture with generated bytes through a
// blit from a buffer; returns nothing, the contents are re-read by cases.
static void WMFillTexture(WMCase *c, id<MTLTexture> texture, NSUInteger bytesPerPixel, uint32_t seed) {
    NSUInteger slices = texture.arrayLength * (texture.textureType == MTLTextureTypeCube ||
                                               texture.textureType == MTLTextureTypeCubeArray ? 6 : 1);
    for (NSUInteger level = 0; level < texture.mipmapLevelCount; level++) {
        NSUInteger w = MAX((NSUInteger)1, texture.width >> level), h = MAX((NSUInteger)1, texture.height >> level);
        NSUInteger d = texture.textureType == MTLTextureType3D ? MAX((NSUInteger)1, texture.depth >> level) : 1;
        for (NSUInteger slice = 0; slice < slices; slice++) {
            NSUInteger length = w * h * d * bytesPerPixel;
            NSMutableData *bytes = [NSMutableData dataWithLength:length];
            WMPattern(bytes.mutableBytes, length, seed + (uint32_t)(level * 64 + slice));
            id<MTLBuffer> source = [c bufferWithBytes:bytes.bytes length:length];
            NSUInteger imagePitch = texture.textureType == MTLTextureType3D ? w * h * bytesPerPixel : 0;
            [c blit:^(id<MTLBlitCommandEncoder> e) {
                // The image pitch is 0 for textures that are not 3D.
                [e copyFromBuffer:source sourceOffset:0 sourceBytesPerRow:w * bytesPerPixel
                    sourceBytesPerImage:imagePitch sourceSize:MTLSizeMake(w, h, d)
                              toTexture:texture destinationSlice:slice destinationLevel:level
                      destinationOrigin:MTLOriginMake(0, 0, 0)];
            }];
        }
    }
}

WMREF_CASE(blitCopyBuffer, "blit.copy-buffer", "blit.copy",
           "copyFromBuffer:sourceOffset:toBuffer:destinationOffset:size: with offsets that are multiples of 4")
{
    uint8_t source[512];
    WMPattern(source, sizeof source, 101);
    id<MTLBuffer> a = [c bufferWithBytes:source length:sizeof source];
    id<MTLBuffer> b = [c buffer:512];
    memset(b.contents, 0x5a, b.length);
    [c blit:^(id<MTLBlitCommandEncoder> e) {
        [e copyFromBuffer:a sourceOffset:12 toBuffer:b destinationOffset:100 size:200];
        // A copy inside one buffer between ranges that do not overlap.
        [e copyFromBuffer:a sourceOffset:0 toBuffer:a destinationOffset:256 size:64];
    }];
    [c data:@"destination" elem:WMElemU8 bytes:b.contents length:b.length rule:WMExact()];
    [c data:@"source-after-self-copy" elem:WMElemU8 bytes:a.contents length:a.length rule:WMExact()];
}

WMREF_CASE(blitCopyBufferUnaligned, "blit.copy-buffer-unaligned", "blit.copy",
           "Buffer copy with byte offsets and size that are not multiples of 4 (valid on iOS)")
{
