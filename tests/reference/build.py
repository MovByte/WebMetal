#!/usr/bin/env python3
"""Build the Metal reference harness (wmref) and its shader library.

    python3 build.py [--platform macos|ios] [--out DIR]

Outputs in DIR (default: build/<platform> next to this file):
    wmref           the harness executable
    wmref.metallib  shaders/*.metal compiled for the platform
    build.json      toolchain versions, target and source digest
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

PLATFORMS = {
    "macos": {"sdk": "macosx", "triple": "arm64-apple-macos{}", "air": "air64-apple-macos{}",
              "min": "14.0", "std": "macos-metal2.4"},
    "ios": {"sdk": "iphoneos", "triple": "arm64-apple-ios{}", "air": "air64-apple-ios{}",
            "min": "17.0", "std": "ios-metal2.4"},
}

FRAMEWORKS = ["Foundation", "Metal", "IOSurface", "QuartzCore", "CoreGraphics"]


def run(command, **kwargs):
    result = subprocess.run(command, capture_output=True, text=True, **kwargs)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit(f"command failed: {' '.join(map(str, command))}")
    if result.stderr.strip():
        sys.stderr.write(result.stderr)
    return result.stdout


def source_files():
    files = [HERE / "build.py"]
    for pattern in ("src/**/*.h", "src/**/*.m", "shaders/**/*.metal", "shaders/**/*.h"):
        files.extend(HERE.glob(pattern))
    return sorted(set(files))


def source_digest(files):
    digest = hashlib.sha256()
    for path in files:
        relative = path.relative_to(HERE).as_posix().encode()
        data = path.read_bytes()
        digest.update(len(relative).to_bytes(8, "little") + relative)
        digest.update(len(data).to_bytes(8, "little") + data)
    return digest.hexdigest()


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--platform", choices=sorted(PLATFORMS), default="macos")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--min-os", help="deployment target (default per platform)")
    parser.add_argument("--metal-std", help="Metal language standard (default per platform)")
    args = parser.parse_args()

    platform = PLATFORMS[args.platform]
    sdk = platform["sdk"]
    minimum = args.min_os or platform["min"]
    std = args.metal_std or platform["std"]
    out = (args.out or HERE / "build" / args.platform).resolve()
    gen = out / "gen"
    air = out / "air"
    for directory in (out, gen, air):
        directory.mkdir(parents=True, exist_ok=True)

    files = source_files()
    info = {
        "platform": args.platform,
        "sdk": sdk,
        "sdk_version": run(["xcrun", "--sdk", sdk, "--show-sdk-version"]).strip(),
        "sdk_build": run(["xcrun", "--sdk", sdk, "--show-sdk-build-version"]).strip(),
        "clang": run(["xcrun", "--sdk", sdk, "clang", "--version"]).splitlines()[0],
        "metal": run(["xcrun", "--sdk", sdk, "metal", "--version"]).splitlines()[0],
        "target": platform["triple"].format(minimum),
        "air_target": platform["air"].format(minimum),
        "metal_std": std,
        "source_sha256": source_digest(files),
    }
    info_json = json.dumps(info, sort_keys=True, separators=(",", ":"))
    header = gen / "WMRefBuildInfo.h"
    header.write_text("// Generated by build.py.\n#define WMREF_BUILD_INFO_JSON " + c_string(info_json) + "\n")

    shaders = sorted((HERE / "shaders").glob("*.metal"))
    airs = []
    for shader in shaders:
        output = air / (shader.stem + ".air")
        run(["xcrun", "--sdk", sdk, "metal", "-c", "-target", info["air_target"], f"-std={std}",
             "-Wall", "-Werror", "-I", str(HERE / "shaders"), str(shader), "-o", str(output)])
        airs.append(output)
    metallib = out / "wmref.metallib"
    run(["xcrun", "--sdk", sdk, "metallib", *map(str, airs), "-o", str(metallib)])

    sources = sorted((HERE / "src").glob("**/*.m"))
    command = ["xcrun", "--sdk", sdk, "clang", "-target", info["target"], "-fobjc-arc",
               "-fobjc-arc-exceptions", "-O1", "-g", "-std=gnu11", "-Wall", "-Wextra",
               "-Wno-unused-parameter", "-Wunguarded-availability", "-Werror",
               "-Wno-error=deprecated-declarations", "-I", str(HERE / "src"), "-I", str(gen)]
    for framework in FRAMEWORKS:
        command += ["-framework", framework]
    command += [*map(str, sources), "-o", str(out / "wmref")]
    run(command)

    (out / "build.json").write_text(json.dumps(info, sort_keys=True, indent=2) + "\n")
    shutil.rmtree(air)
    print(f"built {out / 'wmref'} and {metallib.name} ({len(sources)} sources, {len(shaders)} shader files)")


if __name__ == "__main__":
    main()
